<#
.SYNOPSIS
    Simplifies recursive object schemas in an OpenAPI document.

.DESCRIPTION
    Replaces object schemas with `$recursiveAnchor: true` by the free-form
    schema `{ "type": "object", "additionalProperties": true }`.

    When an eligible anchored schema is a direct branch of a nonempty anyOf
    whose branches all have type object, the containing anyOf schema is replaced
    instead. Parent anyOf collapse takes priority over branch replacement.
    Encounter order is preserved for every noncandidate value.
    Run Split-OpenApiMultiValueTypeEnums.ps1,
    Add-OpenApiOneOfDiscriminators.ps1, Normalize-OpenApiOneOf.ps1,
    Flatten-OpenApiOneOf.ps1, Wrap-OpenApiSingletonTypeEnums.ps1, and
    Sort-OpenApiDocument.ps1 afterward.

.PARAMETER InputPath
    The allOf-flattened and string-simplified OpenAPI JSON document to simplify.

.PARAMETER OutputPath
    The destination JSON file. When omitted, a sibling filename is generated by
    inserting '.recursive-simplified' before '.openapi.json' or the final '.json'
    suffix. If the input already has that suffix, it is atomically rewritten
    in place.

.EXAMPLE
    ./scripts/Simplify-OpenApiRecursiveSchemas.ps1 `
        ./artifacts/openapi-extracts/responses.inlined.flattened.simplified.openapi.json
#>

#Requires -Version 7.0

[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string]$InputPath,

    [Parameter()]
    [string]$OutputPath
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$helperPath = Join-Path $PSScriptRoot "_OpenApiDocument.Helpers.ps1"
if (-not (Test-Path -LiteralPath $helperPath -PathType Leaf)) {
    throw "The shared OpenAPI helper script was not found: $helperPath"
}
. $helperPath

# Eligibility is intentionally exact: both the anchor and scalar object type
# must be present with the expected JSON types and casing.
function Test-IsRecursiveAnchoredOpenApiObjectSchema {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Schema
    )

    if (-not (Test-JsonObjectValue -Value $Schema) -or
        -not (Test-JsonProperty -Object $Schema -Name '$recursiveAnchor')) {
        return $false
    }

    $recursiveAnchor = Get-JsonPropertyValue -Object $Schema -Name '$recursiveAnchor'
    if ($recursiveAnchor -isnot [bool] -or -not $recursiveAnchor) {
        return $false
    }

    $type = Get-JsonPropertyValue -Object $Schema -Name "type"
    return $type -is [string] -and
        [string]::Equals($type, "object", [System.StringComparison]::Ordinal)
}

# A parent is collapsible only when an eligible anchor is one of its direct
# anyOf branches and every direct branch declares the scalar type "object".
# Descendant anchors do not make an otherwise unrelated parent eligible.
function Get-CollapsibleRecursiveOpenApiAnyOfCandidate {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Schema
    )

    $anyOf = Get-JsonPropertyValue -Object $Schema -Name "anyOf"
    if (-not (Test-JsonArrayValue -Value $anyOf) -or @($anyOf).Count -eq 0) {
        return $null
    }

    $anchoredBranchCount = 0
    foreach ($branch in $anyOf) {
        if (-not (Test-JsonObjectValue -Value $branch)) {
            return $null
        }
        $branchType = Get-JsonPropertyValue -Object $branch -Name "type"
        if ($branchType -isnot [string] -or
            -not [string]::Equals($branchType, "object", [System.StringComparison]::Ordinal)) {
            return $null
        }
        if (Test-IsRecursiveAnchoredOpenApiObjectSchema -Schema $branch) {
            $anchoredBranchCount++
        }
    }

    if ($anchoredBranchCount -eq 0) {
        return $null
    }

    return [PSCustomObject]@{
        Branches = $anyOf
        AnchoredBranchCount = $anchoredBranchCount
    }
}

# Replacements deliberately discard every annotation and constraint. Keeping
# this constructor minimal also makes every replacement byte-stable.
function New-FreeFormOpenApiObjectSchema {
    return [ordered]@{
        type = "object"
        additionalProperties = $true
    }
}

# Counts eligible anchors in a subtree before that subtree is discarded. This
# keeps RemovedRecursiveAnchorCount accurate when one parent replacement
# subsumes one or more anchored descendants.
function Get-RecursiveAnchoredOpenApiObjectCount {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter(Mandatory = $true)]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context,

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "Recursive anchor counting exceeds the supported depth of $MaximumDepth."
    }
    if ($null -eq $Value) {
        return 0
    }
    if (Test-JsonArrayValue -Value $Value) {
        # Composition arrays contain schemas; ordinary arrays retain the
        # context inherited from their parent.
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        $count = 0
        foreach ($item in $Value) {
            $count += Get-RecursiveAnchoredOpenApiObjectCount `
                -Value $item `
                -Context $itemContext `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return $count
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return 0
    }

    $count = 0
    if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal) -and
        (Test-IsRecursiveAnchoredOpenApiObjectSchema -Schema $Value)) {
        $count++
    }
    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        $count += Get-RecursiveAnchoredOpenApiObjectCount `
            -Value $property.Value `
            -Context $childContext `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
    return $count
}

# Performs a schema-aware copy of the document. Context prevents schema-like
# keys inside examples and other literal values from being transformed.
function ConvertTo-SimplifiedOpenApiRecursiveSchemaValue {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter(Mandatory = $true)]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context,

        [Parameter(Mandatory = $true)]
        [string]$Breadcrumb,

        [Parameter(Mandatory = $true)]
        [ref]$CollapsedAnyOfCount,

        [Parameter(Mandatory = $true)]
        [ref]$ReplacedRecursiveSchemaCount,

        [Parameter(Mandatory = $true)]
        [ref]$RemovedRecursiveAnchorCount,

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "Recursive schema simplification exceeds the supported depth of $MaximumDepth at '$Breadcrumb'."
    }
    if ($null -eq $Value) {
        return $null
    }
    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        [object[]]$items = [object[]]::new(@($Value).Count)
        for ($index = 0; $index -lt @($Value).Count; $index++) {
            $items[$index] = ConvertTo-SimplifiedOpenApiRecursiveSchemaValue `
                -Value $Value[$index] `
                -Context $itemContext `
                -Breadcrumb "$Breadcrumb/$index" `
                -CollapsedAnyOfCount $CollapsedAnyOfCount `
                -ReplacedRecursiveSchemaCount $ReplacedRecursiveSchemaCount `
                -RemovedRecursiveAnchorCount $RemovedRecursiveAnchorCount `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return ,$items
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return $Value
    }

    if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal)) {
        # Parent collapse must run first. Recursing into the branches first
        # would replace the anchor and erase the evidence needed to collapse
        # the complete all-object anyOf.
        $anyOfCandidate = Get-CollapsibleRecursiveOpenApiAnyOfCandidate -Schema $Value
        if ($null -ne $anyOfCandidate) {
            $RemovedRecursiveAnchorCount.Value += Get-RecursiveAnchoredOpenApiObjectCount `
                -Value $Value `
                -Context Schema
            $CollapsedAnyOfCount.Value++
            return New-FreeFormOpenApiObjectSchema
        }

        # Anchors not subsumed by an eligible parent are replaced individually.
        if (Test-IsRecursiveAnchoredOpenApiObjectSchema -Schema $Value) {
            $RemovedRecursiveAnchorCount.Value += Get-RecursiveAnchoredOpenApiObjectCount `
                -Value $Value `
                -Context Schema
            $ReplacedRecursiveSchemaCount.Value++
            return New-FreeFormOpenApiObjectSchema
        }
    }

    # Noncandidates are copied in encounter order while their schema-valued
    # children are evaluated independently.
    $result = [ordered]@{}
    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        $result[$property.Name] = ConvertTo-SimplifiedOpenApiRecursiveSchemaValue `
            -Value $property.Value `
            -Context $childContext `
            -Breadcrumb "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)" `
            -CollapsedAnyOfCount $CollapsedAnyOfCount `
            -ReplacedRecursiveSchemaCount $ReplacedRecursiveSchemaCount `
            -RemovedRecursiveAnchorCount $RemovedRecursiveAnchorCount `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
    return $result
}

# A separate traversal verifies that the converter did not leave any schema it
# claims to simplify. This catches context or recursion regressions directly.
function Assert-NoSimplifiableOpenApiRecursiveSchemas {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter()]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context = "OpenApi",

        [Parameter()]
        [string]$Breadcrumb = "#",

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "Recursive schema postcondition exceeds the supported depth of $MaximumDepth at '$Breadcrumb'."
    }
    if ($null -eq $Value) {
        return
    }
    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        for ($index = 0; $index -lt @($Value).Count; $index++) {
            Assert-NoSimplifiableOpenApiRecursiveSchemas `
                -Value $Value[$index] `
                -Context $itemContext `
                -Breadcrumb "$Breadcrumb/$index" `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return
    }

    if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal)) {
        if ($null -ne (Get-CollapsibleRecursiveOpenApiAnyOfCandidate -Schema $Value)) {
            throw "Simplified output retained a collapsible recursive anyOf at '$Breadcrumb/anyOf'."
        }
        if (Test-IsRecursiveAnchoredOpenApiObjectSchema -Schema $Value) {
            throw "Simplified output retained an eligible recursive anchor at '$Breadcrumb/`$recursiveAnchor'."
        }
    }

    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        Assert-NoSimplifiableOpenApiRecursiveSchemas `
            -Value $property.Value `
            -Context $childContext `
            -Breadcrumb "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)" `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
}

function ConvertTo-SimplifiedOpenApiRecursiveSchemaDocument {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Document
    )

    $collapsedAnyOfCount = 0
    $replacedRecursiveSchemaCount = 0
    $removedRecursiveAnchorCount = 0
    $simplified = ConvertTo-SimplifiedOpenApiRecursiveSchemaValue `
        -Value $Document `
        -Context OpenApi `
        -Breadcrumb "#" `
        -CollapsedAnyOfCount ([ref]$collapsedAnyOfCount) `
        -ReplacedRecursiveSchemaCount ([ref]$replacedRecursiveSchemaCount) `
        -RemovedRecursiveAnchorCount ([ref]$removedRecursiveAnchorCount)

    # Candidate roots remain at the same pointer, but their descendants may be
    # removed. Reference validation therefore rejects dangling descendant
    # targets instead of inventing a relocation with different semantics.
    Assert-OpenApiReferencesResolve -Document $simplified
    Assert-AdditionalOpenApiReferencesResolve -Document $simplified
    Assert-NoSimplifiableOpenApiRecursiveSchemas -Value $simplified

    return [PSCustomObject]@{
        Document = $simplified
        CollapsedAnyOfCount = $collapsedAnyOfCount
        ReplacedRecursiveSchemaCount = $replacedRecursiveSchemaCount
        RemovedRecursiveAnchorCount = $removedRecursiveAnchorCount
    }
}

# The suffix is inserted once so rerunning the stage can atomically rewrite an
# already-simplified artifact without growing its filename.
function Get-DefaultSimplifiedOpenApiRecursiveSchemaPath {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath
    )

    $fullInputPath = [System.IO.Path]::GetFullPath($InputPath)
    $directory = [System.IO.Path]::GetDirectoryName($fullInputPath)
    $fileName = [System.IO.Path]::GetFileName($fullInputPath)
    if ($fileName.EndsWith(".recursive-simplified.openapi.json", [System.StringComparison]::OrdinalIgnoreCase) -or
        $fileName.EndsWith(".recursive-simplified.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        return $fullInputPath
    }
    if ($fileName.EndsWith(".openapi.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $baseName = $fileName.Substring(0, $fileName.Length - ".openapi.json".Length)
        return Join-Path $directory "$baseName.recursive-simplified.openapi.json"
    }
    if ($fileName.EndsWith(".json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $baseName = $fileName.Substring(0, $fileName.Length - ".json".Length)
        return Join-Path $directory "$baseName.recursive-simplified.json"
    }
    return Join-Path $directory "$fileName.recursive-simplified.json"
}

# The CLI boundary owns path validation, deterministic serialization, and the
# human-readable transformation summary. The conversion functions stay usable
# directly by focused tests and other scripts.
function Invoke-OpenApiRecursiveSchemaSimplifier {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath,

        [Parameter()]
        [string]$OutputPath
    )

    $resolvedInputPath = (Resolve-Path -LiteralPath $InputPath -ErrorAction Stop).ProviderPath
    if (-not [System.IO.File]::Exists($resolvedInputPath)) {
        throw "The OpenAPI input path is not a file: $resolvedInputPath"
    }
    if ([string]::IsNullOrWhiteSpace($OutputPath)) {
        $OutputPath = Get-DefaultSimplifiedOpenApiRecursiveSchemaPath -InputPath $resolvedInputPath
    }
    else {
        $OutputPath = [System.IO.Path]::GetFullPath($OutputPath)
    }

    $document = Read-OpenApiDocument -Path $resolvedInputPath
    $result = ConvertTo-SimplifiedOpenApiRecursiveSchemaDocument -Document $document
    $writtenPath = Write-OpenApiJsonFile -Document $result.Document -Path $OutputPath

    Write-Host ""
    Write-Host "Input: $resolvedInputPath"
    Write-Host "Output: $writtenPath"
    Write-Host "Recursive anyOf compositions collapsed: $($result.CollapsedAnyOfCount)"
    Write-Host "Recursive schemas replaced individually: $($result.ReplacedRecursiveSchemaCount)"
    Write-Host "Recursive anchors removed: $($result.RemovedRecursiveAnchorCount)"

    return $result
}

# Dot-sourcing exposes conversion functions to tests without running the CLI.
if ($MyInvocation.InvocationName -ne ".") {
    if ([string]::IsNullOrWhiteSpace($InputPath)) {
        throw "InputPath is required."
    }
    $null = Invoke-OpenApiRecursiveSchemaSimplifier `
        -InputPath $InputPath `
        -OutputPath $OutputPath
}
