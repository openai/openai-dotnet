<#
.SYNOPSIS
    Canonically sorts an extracted OpenAPI JSON document.

.DESCRIPTION
    Applies deterministic ordering to schema definitions without changing their
    semantics. The sorter supports Inlined, allOf-flattened, and
    string-variant-simplified output from the OpenAPI scripts. It orders schema
    keys, property maps, required arrays, and enum arrays while preserving
    ordinary OpenAPI object order and every non-enum array order.

.PARAMETER InputPath
    The extracted OpenAPI JSON document to sort.

.PARAMETER OutputPath
    The destination JSON file. When omitted, a sibling filename is generated by
    inserting '.sorted' before '.openapi.json' or the final '.json' suffix. An
    already-sorted input is atomically rewritten in place.

.EXAMPLE
    ./scripts/Sort-OpenApiDocument.ps1 `
        ./artifacts/openapi-extracts/responses.inlined.flattened.simplified.openapi.json

#>

#Requires -Version 7.0

[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string]$InputPath,

    [Parameter()]
    [string]$OutputPath
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$helperPath = Join-Path $PSScriptRoot "_OpenApiDocument.Helpers.ps1"
if (-not (Test-Path -LiteralPath $helperPath -PathType Leaf)) {
    throw "The shared OpenAPI helper script was not found: $helperPath"
}
. $helperPath

# Schema keys listed here are emitted first and in this exact order. Remaining
# schema keys follow alphabetically.
$script:PrioritizedSchemaPropertyNames = @(
    "type"
    "description"
    "required"
    "properties"
)

# Required names listed here lead both schema required arrays and required names
# inside properties maps. Optional properties are never promoted.
$script:PrioritizedRequiredPropertyNames = @(
    "type"
)

function Sort-OrdinalStrings {
    param(
        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [string[]]$Values
    )

    [string[]]$sortedValues = @($Values)
    [System.Array]::Sort($sortedValues, [System.StringComparer]::Ordinal)
    return ,$sortedValues
}

# Sorts enum values by compact JSON text while preserving each value's JSON type
# and the relative order of structurally equal values.
function Sort-JsonEnumValues {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [AllowEmptyCollection()]
        [object[]]$Values
    )

    if ($null -eq $Values) {
        return ,([object[]]@($null))
    }

    $sortedEntries = [System.Collections.Generic.List[object]]::new()
    foreach ($value in $Values) {
        $entry = [PSCustomObject]@{
            Key = ConvertTo-Json -InputObject $value -Compress -Depth 100
            Value = $value
        }
        $insertionIndex = $sortedEntries.Count
        for ($index = 0; $index -lt $sortedEntries.Count; $index++) {
            if ([System.StringComparer]::Ordinal.Compare($entry.Key, $sortedEntries[$index].Key) -lt 0) {
                $insertionIndex = $index
                break
            }
        }
        $sortedEntries.Insert($insertionIndex, $entry)
    }

    [object[]]$sortedValues = [object[]]::new($sortedEntries.Count)
    for ($index = 0; $index -lt $sortedEntries.Count; $index++) {
        $sortedValues[$index] = $sortedEntries[$index].Value
    }
    return ,$sortedValues
}

function Get-OrderedRequiredPropertyNames {
    param(
        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [string[]]$RequiredNames
    )

    $availableNames = [System.Collections.Generic.HashSet[string]]::new(
        [System.StringComparer]::Ordinal
    )
    foreach ($requiredName in $RequiredNames) {
        $null = $availableNames.Add($requiredName)
    }

    $emittedNames = [System.Collections.Generic.HashSet[string]]::new(
        [System.StringComparer]::Ordinal
    )
    $orderedNames = [System.Collections.Generic.List[string]]::new()
    foreach ($requiredName in $script:PrioritizedRequiredPropertyNames) {
        if ($availableNames.Contains($requiredName) -and $emittedNames.Add($requiredName)) {
            $orderedNames.Add($requiredName)
        }
    }

    [string[]]$remainingNames = @($availableNames | Where-Object {
        -not $emittedNames.Contains($_)
    })
    foreach ($requiredName in (Sort-OrdinalStrings -Values $remainingNames)) {
        if ($emittedNames.Add($requiredName)) {
            $orderedNames.Add($requiredName)
        }
    }
    return [string[]]$orderedNames
}

function Get-OrderedSchemaPropertyNames {
    param(
        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [string[]]$PropertyNames,

        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [System.Collections.Generic.HashSet[string]]$RequiredNames
    )

    $availableNames = [System.Collections.Generic.HashSet[string]]::new(
        [System.StringComparer]::Ordinal
    )
    foreach ($propertyName in $PropertyNames) {
        $null = $availableNames.Add($propertyName)
    }

    $emittedNames = [System.Collections.Generic.HashSet[string]]::new(
        [System.StringComparer]::Ordinal
    )
    $orderedNames = [System.Collections.Generic.List[string]]::new()
    [string[]]$requiredNameValues = @($RequiredNames | ForEach-Object { $_ })
    foreach ($propertyName in (Get-OrderedRequiredPropertyNames -RequiredNames $requiredNameValues)) {
        if ($availableNames.Contains($propertyName) -and $emittedNames.Add($propertyName)) {
            $orderedNames.Add($propertyName)
        }
    }

    [string[]]$optionalNames = @($PropertyNames | Where-Object {
        -not $RequiredNames.Contains($_)
    })
    foreach ($propertyName in (Sort-OrdinalStrings -Values $optionalNames)) {
        if ($emittedNames.Add($propertyName)) {
            $orderedNames.Add($propertyName)
        }
    }
    return ,([string[]]$orderedNames)
}

function ConvertTo-OrderedSchemaDefinition {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Schema
    )

    $orderedSchema = [ordered]@{}
    $emittedNames = [System.Collections.Generic.HashSet[string]]::new(
        [System.StringComparer]::Ordinal
    )
    foreach ($propertyName in $script:PrioritizedSchemaPropertyNames) {
        if ($emittedNames.Add($propertyName) -and
            (Test-JsonProperty -Object $Schema -Name $propertyName)) {
            $orderedSchema[$propertyName] = Get-JsonPropertyValue -Object $Schema -Name $propertyName
        }
    }

    [string[]]$remainingNames = @(Get-JsonProperties -Value $Schema | Where-Object {
        -not $emittedNames.Contains($_.Name)
    } | ForEach-Object Name)
    foreach ($propertyName in (Sort-OrdinalStrings -Values $remainingNames)) {
        $orderedSchema[$propertyName] = Get-JsonPropertyValue -Object $Schema -Name $propertyName
    }
    return $orderedSchema
}

# Recursively applies canonical ordering only to schema definitions. It does not
# omit fields or alter non-schema object and non-enum array order.
function ConvertTo-SortedOpenApiValue {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter()]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context = "OpenApi",

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "JSON sorting exceeds the supported depth of $MaximumDepth."
    }
    if ($null -eq $Value) {
        return $null
    }
    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        [object[]]$items = [object[]]::new($Value.Count)
        for ($index = 0; $index -lt $Value.Count; $index++) {
            $items[$index] = ConvertTo-SortedOpenApiValue `
                -Value $Value[$index] `
                -Context $itemContext `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return ,$items
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return $Value
    }
    if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
        $Context = "Schema"
    }

    $requiredNames = [System.Collections.Generic.HashSet[string]]::new(
        [System.StringComparer]::Ordinal
    )
    if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal)) {
        $required = Get-JsonPropertyValue -Object $Value -Name "required"
        if (Test-JsonArrayValue -Value $required) {
            foreach ($requiredName in $required) {
                if ($requiredName -isnot [string]) {
                    throw "Every required name must be a string."
                }
                $null = $requiredNames.Add($requiredName)
            }
        }
    }

    $result = [ordered]@{}
    foreach ($property in (Get-JsonProperties -Value $Value)) {
        if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal) -and
            [string]::Equals($property.Name, "enum", [System.StringComparison]::Ordinal) -and
            (Test-JsonArrayValue -Value $property.Value)) {
            [object[]]$enumValues = [object[]]::new($property.Value.Count)
            for ($index = 0; $index -lt $property.Value.Count; $index++) {
                $enumValues[$index] = ConvertTo-SortedOpenApiValue `
                    -Value $property.Value[$index] `
                    -Context Literal `
                    -Depth ($Depth + 1) `
                    -MaximumDepth $MaximumDepth
            }
            $result[$property.Name] = Sort-JsonEnumValues -Values $enumValues
            continue
        }

        if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal) -and
            [string]::Equals($property.Name, "required", [System.StringComparison]::Ordinal) -and
            (Test-JsonArrayValue -Value $property.Value)) {
            [string[]]$requiredNameValues = @(
                foreach ($requiredName in $property.Value) {
                    if ($requiredName -isnot [string]) {
                        throw "Every required name must be a string."
                    }
                    $requiredName
                }
            )
            $result[$property.Name] = @(
                Get-OrderedRequiredPropertyNames -RequiredNames $requiredNameValues
            )
            continue
        }

        if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal) -and
            [string]::Equals($property.Name, "properties", [System.StringComparison]::Ordinal) -and
            (Test-JsonObjectValue -Value $property.Value)) {
            [string[]]$propertyNames = @(
                Get-JsonProperties -Value $property.Value | ForEach-Object Name
            )
            $orderedProperties = [ordered]@{}
            foreach ($propertyName in (Get-OrderedSchemaPropertyNames `
                -PropertyNames $propertyNames `
                -RequiredNames $requiredNames)) {
                $orderedProperties[$propertyName] = ConvertTo-SortedOpenApiValue `
                    -Value (Get-JsonPropertyValue -Object $property.Value -Name $propertyName) `
                    -Context Schema `
                    -Depth ($Depth + 1) `
                    -MaximumDepth $MaximumDepth
            }
            $result[$property.Name] = $orderedProperties
            continue
        }

        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        $result[$property.Name] = ConvertTo-SortedOpenApiValue `
            -Value $property.Value `
            -Context $childContext `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }

    if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal)) {
        return ConvertTo-OrderedSchemaDefinition -Schema $result
    }
    return $result
}

function ConvertTo-SortedOpenApiDocument {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Document
    )

    $sorted = ConvertTo-SortedOpenApiValue -Value $Document
    Assert-OpenApiReferencesResolve -Document $sorted
    return $sorted
}

function Get-DefaultSortedOpenApiPath {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath
    )

    $fullInputPath = [System.IO.Path]::GetFullPath($InputPath)
    $directory = [System.IO.Path]::GetDirectoryName($fullInputPath)
    $fileName = [System.IO.Path]::GetFileName($fullInputPath)
    if ($fileName.EndsWith(".sorted.openapi.json", [System.StringComparison]::OrdinalIgnoreCase) -or
        $fileName.EndsWith(".sorted.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        return $fullInputPath
    }
    if ($fileName.EndsWith(".openapi.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $baseName = $fileName.Substring(0, $fileName.Length - ".openapi.json".Length)
        return Join-Path $directory "$baseName.sorted.openapi.json"
    }
    if ($fileName.EndsWith(".json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $baseName = $fileName.Substring(0, $fileName.Length - ".json".Length)
        return Join-Path $directory "$baseName.sorted.json"
    }
    return Join-Path $directory "$fileName.sorted.json"
}

function Invoke-OpenApiDocumentSorter {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath,

        [Parameter()]
        [string]$OutputPath
    )

    $resolvedInputPath = (Resolve-Path -LiteralPath $InputPath -ErrorAction Stop).ProviderPath
    if (-not [System.IO.File]::Exists($resolvedInputPath)) {
        throw "The OpenAPI input path is not a file: $resolvedInputPath"
    }
    if ([string]::IsNullOrWhiteSpace($OutputPath)) {
        $OutputPath = Get-DefaultSortedOpenApiPath -InputPath $resolvedInputPath
    }
    else {
        $OutputPath = [System.IO.Path]::GetFullPath($OutputPath)
    }

    $document = Read-OpenApiDocument -Path $resolvedInputPath
    $sorted = ConvertTo-SortedOpenApiDocument -Document $document
    $writtenPath = Write-OpenApiJsonFile -Document $sorted -Path $OutputPath

    Write-Host ""
    Write-Host "Input: $resolvedInputPath"
    Write-Host "Output: $writtenPath"

    return $sorted
}

if ($MyInvocation.InvocationName -ne ".") {
    if ([string]::IsNullOrWhiteSpace($InputPath)) {
        throw "InputPath is required."
    }
    $null = Invoke-OpenApiDocumentSorter -InputPath $InputPath -OutputPath $OutputPath
}
