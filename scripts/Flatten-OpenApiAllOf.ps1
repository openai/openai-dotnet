<#
.SYNOPSIS
    Flattens all allOf schema compositions in an Inlined OpenAPI document.

.DESCRIPTION
    Reads inlined JSON produced by Inline-OpenApiReferences.ps1, recursively
    merges every allOf composition into a single schema, relocates affected local
    JSON pointers, and writes a separate flattened OpenAPI document while
    preserving encounter order. Run Simplify-OpenApiStringVariants.ps1,
    Simplify-OpenApiRecursiveSchemas.ps1, Add-OpenApiOneOfDiscriminators.ps1,
    Normalize-OpenApiOneOf.ps1, Flatten-OpenApiOneOf.ps1, and then
    Sort-OpenApiDocument.ps1 afterward to consolidate eligible nested string
    unions, replace recursive objects, infer missing type discriminators,
    normalize and flatten oneOf metadata, and produce canonical ordering.
    Flattening is byte-idempotent; running the script against already-flat
    output preserves its JSON bytes.

.PARAMETER InputPath
    The Inlined OpenAPI JSON document to flatten.

.PARAMETER OutputPath
    The destination JSON file. When omitted, a sibling filename is generated by
    inserting '.flattened' before '.openapi.json' or the final '.json' suffix.
    If the input already has that suffix, it is atomically rewritten in place.

.EXAMPLE
    ./scripts/Flatten-OpenApiAllOf.ps1 `
        ./artifacts/openapi-extracts/responses.inlined.openapi.json

.EXAMPLE
    ./scripts/Flatten-OpenApiAllOf.ps1 `
        ./artifacts/openapi-extracts/responses.inlined.openapi.json `
        -OutputPath ./artifacts/openapi-extracts/responses.final.json

.EXAMPLE
    ./scripts/Flatten-OpenApiAllOf.ps1 `
        ./artifacts/openapi-extracts/responses.inlined.openapi.json
    ./scripts/Simplify-OpenApiStringVariants.ps1 `
        ./artifacts/openapi-extracts/responses.inlined.flattened.openapi.json
    ./scripts/Simplify-OpenApiRecursiveSchemas.ps1 `
        ./artifacts/openapi-extracts/responses.inlined.flattened.simplified.openapi.json
    ./scripts/Split-OpenApiMultiValueTypeEnums.ps1 `
        ./artifacts/openapi-extracts/responses.inlined.flattened.simplified.recursive-simplified.openapi.json
    ./scripts/Add-OpenApiOneOfDiscriminators.ps1 `
        ./artifacts/openapi-extracts/responses.inlined.flattened.simplified.recursive-simplified.type-enum-split.openapi.json
    ./scripts/Normalize-OpenApiOneOf.ps1 `
        ./artifacts/openapi-extracts/responses.inlined.flattened.simplified.recursive-simplified.type-enum-split.oneof-discriminated.openapi.json
    ./scripts/Flatten-OpenApiOneOf.ps1 `
        ./artifacts/openapi-extracts/responses.inlined.flattened.simplified.recursive-simplified.type-enum-split.oneof-discriminated.oneof-normalized.openapi.json
    ./scripts/Wrap-OpenApiSingletonTypeEnums.ps1 `
        ./artifacts/openapi-extracts/responses.inlined.flattened.simplified.recursive-simplified.type-enum-split.oneof-discriminated.oneof-normalized.oneof-flattened.openapi.json
    ./scripts/Sort-OpenApiDocument.ps1 `
        ./artifacts/openapi-extracts/responses.inlined.flattened.simplified.recursive-simplified.type-enum-split.oneof-discriminated.oneof-normalized.oneof-flattened.singleton-type-wrapped.openapi.json
#>

#Requires -Version 7.0

[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string]$InputPath,

    [Parameter()]
    [string]$OutputPath
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$helperPath = Join-Path $PSScriptRoot "_OpenApiDocument.Helpers.ps1"
if (-not (Test-Path -LiteralPath $helperPath -PathType Leaf)) {
    throw "The shared OpenAPI helper script was not found: $helperPath"
}
. $helperPath

# Recursively flattens schema allOf compositions while preserving every other
# object and array shape. Nested compositions are flattened before their parent.
function ConvertTo-FlattenedOpenApiAllOfValue {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter(Mandatory = $true)]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context,

        [Parameter(Mandatory = $true)]
        [string]$Breadcrumb,

        [Parameter(Mandatory = $true)]
        [System.Collections.Generic.Dictionary[string, string]]$Relocations,

        [Parameter(Mandatory = $true)]
        [ref]$FlattenedCount,

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "allOf flattening exceeds the supported depth of $MaximumDepth at '$Breadcrumb'."
    }
    if ($null -eq $Value) {
        return $null
    }

    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        [object[]]$items = [object[]]::new($Value.Count)
        for ($index = 0; $index -lt $Value.Count; $index++) {
            $items[$index] = ConvertTo-FlattenedOpenApiAllOfValue `
                -Value $Value[$index] `
                -Context $itemContext `
                -Breadcrumb "$Breadcrumb/$index" `
                -Relocations $Relocations `
                -FlattenedCount $FlattenedCount `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return ,$items
    }

    if (-not (Test-JsonObjectValue -Value $Value)) {
        return $Value
    }
    if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
        $Context = "Schema"
    }

    if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal) -and
        (Test-JsonProperty -Object $Value -Name "allOf")) {
        $allOfBranches = Get-JsonPropertyValue -Object $Value -Name "allOf"
        if (-not (Test-JsonArrayValue -Value $allOfBranches)) {
            throw "The allOf keyword at '$Breadcrumb/allOf' must be an array."
        }
        if ($allOfBranches.Count -eq 0) {
            throw "The allOf array at '$Breadcrumb/allOf' must contain at least one object definition."
        }

        $definitions = [System.Collections.Generic.List[object]]::new()
        $definitionBreadcrumbs = [System.Collections.Generic.List[string]]::new()
        for ($index = 0; $index -lt $allOfBranches.Count; $index++) {
            $branchBreadcrumb = "$Breadcrumb/allOf/$index"
            if (-not (Test-JsonObjectValue -Value $allOfBranches[$index])) {
                throw "The allOf branch at '$branchBreadcrumb' must be an object definition."
            }
            Add-OpenApiPointerRelocation `
                -Relocations $Relocations `
                -SourcePrefix $branchBreadcrumb `
                -DestinationPrefix $Breadcrumb
            $definitions.Add((ConvertTo-FlattenedOpenApiAllOfValue `
                -Value $allOfBranches[$index] `
                -Context Schema `
                -Breadcrumb $branchBreadcrumb `
                -Relocations $Relocations `
                -FlattenedCount $FlattenedCount `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth))
            $definitionBreadcrumbs.Add($branchBreadcrumb)
        }

        $containingSchema = [ordered]@{}
        foreach ($property in (Get-JsonProperties -Value $Value)) {
            if ([string]::Equals($property.Name, "allOf", [System.StringComparison]::Ordinal)) {
                continue
            }
            $childContext = Get-OpenApiSchemaChildContext `
                -ParentContext Schema `
                -PropertyName $property.Name `
                -PropertyValue $property.Value
            $containingSchema[$property.Name] = ConvertTo-FlattenedOpenApiAllOfValue `
                -Value $property.Value `
                -Context $childContext `
                -Breadcrumb "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)" `
                -Relocations $Relocations `
                -FlattenedCount $FlattenedCount `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        if ($containingSchema.Count -gt 0) {
            $definitions.Add($containingSchema)
            $definitionBreadcrumbs.Add($Breadcrumb)
        }

        $FlattenedCount.Value++
        return Merge-OpenApiSchemaDefinitions `
            -Definitions @($definitions) `
            -DefinitionBreadcrumbs @($definitionBreadcrumbs) `
            -Breadcrumb $Breadcrumb
    }

    $result = [ordered]@{}
    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        $result[$property.Name] = ConvertTo-FlattenedOpenApiAllOfValue `
            -Value $property.Value `
            -Context $childContext `
            -Breadcrumb "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)" `
            -Relocations $Relocations `
            -FlattenedCount $FlattenedCount `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
    return $result
}

# Rejects any allOf keyword that survives final flattening.
function Assert-NoOpenApiAllOf {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter()]
        [string]$Breadcrumb = "#"
    )

    if ($null -eq $Value) {
        return
    }
    if (Test-JsonArrayValue -Value $Value) {
        for ($index = 0; $index -lt $Value.Count; $index++) {
            Assert-NoOpenApiAllOf -Value $Value[$index] -Breadcrumb "$Breadcrumb/$index"
        }
        return
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return
    }
    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $propertyBreadcrumb = "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)"
        if ([string]::Equals($property.Name, "allOf", [System.StringComparison]::Ordinal)) {
            throw "Flattened output retained allOf at '$propertyBreadcrumb'."
        }
        Assert-NoOpenApiAllOf -Value $property.Value -Breadcrumb $propertyBreadcrumb
    }
}

# Converts an Inlined extractor document to its fully flattened representation.
function ConvertTo-FlattenedOpenApiDocument {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Document
    )

    $relocations = [System.Collections.Generic.Dictionary[string, string]]::new(
        [System.StringComparer]::Ordinal
    )
    $flattenedCount = 0
    $flattened = ConvertTo-FlattenedOpenApiAllOfValue `
        -Value $Document `
        -Context OpenApi `
        -Breadcrumb "#" `
        -Relocations $relocations `
        -FlattenedCount ([ref]$flattenedCount)
    $relocated = ConvertTo-RelocatedOpenApiPointers `
        -Value $flattened `
        -Relocations $relocations
    Assert-OpenApiReferencesResolve -Document $relocated
    Assert-AdditionalOpenApiReferencesResolve -Document $relocated
    Assert-NoOpenApiAllOf -Value $relocated

    return [PSCustomObject]@{
        Document = $relocated
        FlattenedCount = $flattenedCount
        RelocationCount = $relocations.Count
    }
}

# Derives a sibling flattened filename without replacing the extractor output.
function Get-DefaultFlattenedOpenApiPath {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath
    )

    $fullInputPath = [System.IO.Path]::GetFullPath($InputPath)
    $directory = [System.IO.Path]::GetDirectoryName($fullInputPath)
    $fileName = [System.IO.Path]::GetFileName($fullInputPath)
    if ($fileName.EndsWith(".flattened.openapi.json", [System.StringComparison]::OrdinalIgnoreCase) -or
        $fileName.EndsWith(".flattened.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        return $fullInputPath
    }
    if ($fileName.EndsWith(".openapi.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $baseName = $fileName.Substring(0, $fileName.Length - ".openapi.json".Length)
        return Join-Path $directory "$baseName.flattened.openapi.json"
    }
    if ($fileName.EndsWith(".json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $baseName = $fileName.Substring(0, $fileName.Length - ".json".Length)
        return Join-Path $directory "$baseName.flattened.json"
    }
    return Join-Path $directory "$fileName.flattened.json"
}

function Invoke-OpenApiAllOfFlattener {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath,

        [Parameter()]
        [string]$OutputPath
    )

    $resolvedInputPath = (Resolve-Path -LiteralPath $InputPath -ErrorAction Stop).ProviderPath
    if (-not [System.IO.File]::Exists($resolvedInputPath)) {
        throw "The OpenAPI input path is not a file: $resolvedInputPath"
    }
    if ([string]::IsNullOrWhiteSpace($OutputPath)) {
        $OutputPath = Get-DefaultFlattenedOpenApiPath -InputPath $resolvedInputPath
    }
    else {
        $OutputPath = [System.IO.Path]::GetFullPath($OutputPath)
    }

    $document = Read-OpenApiDocument -Path $resolvedInputPath
    $result = ConvertTo-FlattenedOpenApiDocument -Document $document
    $writtenPath = Write-OpenApiJsonFile -Document $result.Document -Path $OutputPath

    Write-Host ""
    Write-Host "Input: $resolvedInputPath"
    Write-Host "Output: $writtenPath"
    Write-Host "allOf compositions flattened: $($result.FlattenedCount)"

    return $result
}

# Dot-sourcing exposes the conversion functions to tests without running the
# command-line entry point.
if ($MyInvocation.InvocationName -ne ".") {
    if ([string]::IsNullOrWhiteSpace($InputPath)) {
        throw "InputPath is required."
    }
    $null = Invoke-OpenApiAllOfFlattener `
        -InputPath $InputPath `
        -OutputPath $OutputPath
}
