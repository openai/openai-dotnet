<#
.SYNOPSIS
    Splits required multi-value object type enums into singleton variants.

.DESCRIPTION
    Finds Schema Objects whose direct scalar type is `object`, whose required
    property `type` is a string enum with more than one distinct value, and
    creates one complete object variant per enum value. Each generated variant
    retains a singleton enum array and every other source constraint.

    Qualifying direct oneOf and anyOf branches expand in place. Qualifying
    schemas in other positions become transparent oneOf wrappers. Schema-like
    literal values are ignored. Ambiguous local pointer targets and duplicated
    resolution scopes fail before output is written.

.PARAMETER InputPath
    The recursive-simplified OpenAPI JSON document to split.

.PARAMETER OutputPath
    The destination JSON file. When omitted, a sibling filename is generated by
    inserting '.type-enum-split' before '.openapi.json' or the final '.json'
    suffix. Already split input is atomically rewritten in place.

.EXAMPLE
    ./scripts/Split-OpenApiMultiValueTypeEnums.ps1 `
        ./artifacts/openapi-extracts/responses.inlined.flattened.simplified.recursive-simplified.openapi.json
#>

#Requires -Version 7.0

[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string]$InputPath,

    [Parameter()]
    [string]$OutputPath
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$helperPath = Join-Path $PSScriptRoot "_OpenApiDocument.Helpers.ps1"
if (-not (Test-Path -LiteralPath $helperPath -PathType Leaf)) {
    throw "The shared OpenAPI helper script was not found: $helperPath"
}
. $helperPath

function Get-SplittableOpenApiMultiValueTypeEnumPlan {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Schema,

        [Parameter(Mandatory = $true)]
        [string]$Breadcrumb
    )

    if (-not (Test-JsonObjectValue -Value $Schema)) {
        return $null
    }
    $schemaType = Get-JsonPropertyValue -Object $Schema -Name "type"
    if ($schemaType -isnot [string] -or
        -not [string]::Equals($schemaType, "object", [System.StringComparison]::Ordinal)) {
        return $null
    }

    $properties = Get-JsonPropertyValue -Object $Schema -Name "properties"
    if (-not (Test-JsonObjectValue -Value $properties) -or
        -not (Test-JsonProperty -Object $properties -Name "type")) {
        return $null
    }
    $typeProperty = Get-JsonPropertyValue -Object $properties -Name "type"
    if (-not (Test-JsonObjectValue -Value $typeProperty)) {
        return $null
    }
    $propertyType = Get-JsonPropertyValue -Object $typeProperty -Name "type"
    if ($propertyType -isnot [string] -or
        -not [string]::Equals($propertyType, "string", [System.StringComparison]::Ordinal)) {
        return $null
    }

    $enum = Get-JsonPropertyValue -Object $typeProperty -Name "enum"
    if (-not (Test-JsonArrayValue -Value $enum) -or $enum.Count -le 1) {
        return $null
    }

    $required = Get-JsonPropertyValue -Object $Schema -Name "required"
    if (-not (Test-JsonArrayValue -Value $required) -or
        @($required | Where-Object {
            $_ -is [string] -and
            [string]::Equals($_, "type", [System.StringComparison]::Ordinal)
        }).Count -eq 0) {
        return $null
    }

    $values = [System.Collections.Generic.List[string]]::new()
    $seenValues = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::Ordinal)
    for ($index = 0; $index -lt $enum.Count; $index++) {
        $value = $enum[$index]
        if ($value -isnot [string]) {
            throw "Type enum value at '$Breadcrumb/properties/type/enum/$index' must be a string."
        }
        if (-not $seenValues.Add($value)) {
            throw "Type enum at '$Breadcrumb/properties/type/enum' contains duplicate value '$value'."
        }
        $values.Add($value)
    }

    return [PSCustomObject]@{
        Values = [string[]]$values.ToArray()
    }
}

function Get-OpenApiMultiValueTypeEnumScopeKeywordOccurrence {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter(Mandatory = $true)]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context,

        [Parameter(Mandatory = $true)]
        [string]$Breadcrumb,

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "Type enum scope inspection exceeds the supported depth of $MaximumDepth at '$Breadcrumb'."
    }
    if ($null -eq $Value -or [string]::Equals($Context, "Literal", [System.StringComparison]::Ordinal)) {
        return $null
    }
    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        for ($index = 0; $index -lt $Value.Count; $index++) {
            $occurrence = Get-OpenApiMultiValueTypeEnumScopeKeywordOccurrence `
                -Value $Value[$index] `
                -Context $itemContext `
                -Breadcrumb "$Breadcrumb/$index" `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
            if ($null -ne $occurrence) {
                return $occurrence
            }
        }
        return $null
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return $null
    }

    if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal)) {
        foreach ($keyword in @('$id', '$anchor', '$dynamicAnchor', '$recursiveAnchor')) {
            if (Test-JsonProperty -Object $Value -Name $keyword) {
                return [PSCustomObject]@{
                    Keyword = $keyword
                    Breadcrumb = "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $keyword)"
                }
            }
        }
    }

    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        $occurrence = Get-OpenApiMultiValueTypeEnumScopeKeywordOccurrence `
            -Value $property.Value `
            -Context $childContext `
            -Breadcrumb "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)" `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
        if ($null -ne $occurrence) {
            return $occurrence
        }
    }
    return $null
}

function Add-OpenApiMultiValueTypeEnumSplitCandidates {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter(Mandatory = $true)]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context,

        [Parameter(Mandatory = $true)]
        [string]$Breadcrumb,

        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [System.Collections.Generic.List[object]]$Candidates,

        [Parameter()]
        [AllowNull()]
        [ValidateSet("oneOf", "anyOf")]
        [string]$DirectCompositionName,

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "Type enum split discovery exceeds the supported depth of $MaximumDepth at '$Breadcrumb'."
    }
    if ($null -eq $Value) {
        return
    }
    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        for ($index = 0; $index -lt $Value.Count; $index++) {
            Add-OpenApiMultiValueTypeEnumSplitCandidates `
                -Value $Value[$index] `
                -Context $itemContext `
                -Breadcrumb "$Breadcrumb/$index" `
                -Candidates $Candidates `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return
    }

    if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal)) {
        $plan = Get-SplittableOpenApiMultiValueTypeEnumPlan -Schema $Value -Breadcrumb $Breadcrumb
        if ($null -ne $plan) {
            $scopeOccurrence = Get-OpenApiMultiValueTypeEnumScopeKeywordOccurrence `
                -Value $Value `
                -Context Schema `
                -Breadcrumb $Breadcrumb
            if ($null -ne $scopeOccurrence) {
                throw "Cannot split schema at '$Breadcrumb' because scope-sensitive keyword '$($scopeOccurrence.Keyword)' at '$($scopeOccurrence.Breadcrumb)' would be duplicated."
            }
            $Candidates.Add([PSCustomObject]@{
                Breadcrumb = $Breadcrumb
                Mode = if ($DirectCompositionName -in @("oneOf", "anyOf")) { "Expanded" } else { "Wrapped" }
                CompositionName = $DirectCompositionName
                Values = [string[]]$plan.Values
            })
        }
    }

    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        $propertyBreadcrumb = "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)"
        if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal) -and
            $property.Name -in @("oneOf", "anyOf") -and
            (Test-JsonArrayValue -Value $property.Value)) {
            for ($index = 0; $index -lt $property.Value.Count; $index++) {
                Add-OpenApiMultiValueTypeEnumSplitCandidates `
                    -Value $property.Value[$index] `
                    -Context Schema `
                    -Breadcrumb "$propertyBreadcrumb/$index" `
                    -Candidates $Candidates `
                    -DirectCompositionName $property.Name `
                    -Depth ($Depth + 1) `
                    -MaximumDepth $MaximumDepth
            }
            continue
        }
        Add-OpenApiMultiValueTypeEnumSplitCandidates `
            -Value $property.Value `
            -Context $childContext `
            -Breadcrumb $propertyBreadcrumb `
            -Candidates $Candidates `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
}

function Get-OpenApiMultiValueTypeEnumReferenceOccurrences {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter()]
        [ValidateSet("Default", "Discriminator", "Mapping")]
        [string]$Context = "Default",

        [Parameter()]
        [string]$Breadcrumb = "#",

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "Type enum reference discovery exceeds the supported depth of $MaximumDepth at '$Breadcrumb'."
    }
    if ($null -eq $Value) {
        return
    }
    if (Test-JsonArrayValue -Value $Value) {
        for ($index = 0; $index -lt $Value.Count; $index++) {
            Get-OpenApiMultiValueTypeEnumReferenceOccurrences `
                -Value $Value[$index] `
                -Context Default `
                -Breadcrumb "$Breadcrumb/$index" `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return
    }

    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $propertyBreadcrumb = "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)"
        $isMappingValue = [string]::Equals($Context, "Mapping", [System.StringComparison]::Ordinal) -and
            $property.Value -is [string]
        $isReferenceValue = @('$ref', '$dynamicRef', '$recursiveRef') -ccontains $property.Name -and
            $property.Value -is [string]
        if ($isMappingValue -or $isReferenceValue) {
            [PSCustomObject]@{
                Pointer = $property.Value
                Breadcrumb = $propertyBreadcrumb
            }
        }

        $childContext = "Default"
        if ([string]::Equals($Context, "Default", [System.StringComparison]::Ordinal) -and
            [string]::Equals($property.Name, "discriminator", [System.StringComparison]::Ordinal)) {
            $childContext = "Discriminator"
        }
        elseif ([string]::Equals($Context, "Discriminator", [System.StringComparison]::Ordinal) -and
            [string]::Equals($property.Name, "mapping", [System.StringComparison]::Ordinal)) {
            $childContext = "Mapping"
        }

        Get-OpenApiMultiValueTypeEnumReferenceOccurrences `
            -Value $property.Value `
            -Context $childContext `
            -Breadcrumb $propertyBreadcrumb `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
}

function Assert-OpenApiMultiValueTypeEnumSplitReferencesAreSafe {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Document,

        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [object[]]$Candidates
    )

    foreach ($occurrence in @(Get-OpenApiMultiValueTypeEnumReferenceOccurrences -Value $Document)) {
        if ($occurrence.Pointer -isnot [string] -or
            -not $occurrence.Pointer.StartsWith("#/", [System.StringComparison]::Ordinal)) {
            continue
        }
        $target = Get-CanonicalJsonPointer -Pointer $occurrence.Pointer
        foreach ($candidate in $Candidates) {
            $isAtCandidate = [string]::Equals($target, $candidate.Breadcrumb, [System.StringComparison]::Ordinal)
            $isBelowCandidate = $target.Length -gt $candidate.Breadcrumb.Length -and
                $target.StartsWith($candidate.Breadcrumb, [System.StringComparison]::Ordinal) -and
                $target[$candidate.Breadcrumb.Length] -eq '/'
            if (($candidate.Mode -ceq "Expanded" -and ($isAtCandidate -or $isBelowCandidate)) -or
                ($candidate.Mode -ceq "Wrapped" -and $isBelowCandidate)) {
                throw "Cannot split schema at '$($candidate.Breadcrumb)' because reference at '$($occurrence.Breadcrumb)' targets ambiguous location '$($occurrence.Pointer)'."
            }
        }
    }
}

function Add-OpenApiMultiValueTypeEnumPointerRelocation {
    param(
        [Parameter(Mandatory = $true)]
        [System.Collections.Generic.Dictionary[string, string]]$Relocations,

        [Parameter(Mandatory = $true)]
        [string]$SourcePrefix,

        [Parameter(Mandatory = $true)]
        [string]$DestinationPrefix
    )

    if (-not [string]::Equals($SourcePrefix, $DestinationPrefix, [System.StringComparison]::Ordinal)) {
        Add-OpenApiPointerRelocation `
            -Relocations $Relocations `
            -SourcePrefix $SourcePrefix `
            -DestinationPrefix $DestinationPrefix
    }
}

function New-OpenApiMultiValueTypeEnumVariants {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Schema,

        [Parameter(Mandatory = $true)]
        [string[]]$Values
    )

    $variants = [System.Collections.Generic.List[object]]::new()
    foreach ($value in $Values) {
        $variant = Copy-JsonValue -Value $Schema
        $typeProperty = Get-JsonPropertyValue `
            -Object (Get-JsonPropertyValue -Object $variant -Name "properties") `
            -Name "type"
        $typeProperty["enum"] = [object[]]@($value)
        $variants.Add($variant)
    }
    return [object[]]$variants.ToArray()
}

function ConvertTo-SplitOpenApiMultiValueTypeEnumValue {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter(Mandatory = $true)]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context,

        [Parameter(Mandatory = $true)]
        [string]$SourceBreadcrumb,

        [Parameter(Mandatory = $true)]
        [string]$DestinationBreadcrumb,

        [Parameter(Mandatory = $true)]
        [System.Collections.Generic.Dictionary[string, object]]$CandidateByBreadcrumb,

        [Parameter(Mandatory = $true)]
        [System.Collections.Generic.Dictionary[string, string]]$Relocations,

        [Parameter()]
        [switch]$SuppressCurrentCandidate,

        [Parameter()]
        [switch]$SuppressRelocations,

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "Type enum splitting exceeds the supported depth of $MaximumDepth at '$SourceBreadcrumb'."
    }
    if ($null -eq $Value) {
        return $null
    }
    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        [object[]]$items = [object[]]::new($Value.Count)
        for ($index = 0; $index -lt $Value.Count; $index++) {
            $items[$index] = ConvertTo-SplitOpenApiMultiValueTypeEnumValue `
                -Value $Value[$index] `
                -Context $itemContext `
                -SourceBreadcrumb "$SourceBreadcrumb/$index" `
                -DestinationBreadcrumb "$DestinationBreadcrumb/$index" `
                -CandidateByBreadcrumb $CandidateByBreadcrumb `
                -Relocations $Relocations `
                -SuppressRelocations:$SuppressRelocations `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return ,$items
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return $Value
    }
    if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
        $Context = "Schema"
    }

    if (-not $SuppressCurrentCandidate -and
        $CandidateByBreadcrumb.ContainsKey($SourceBreadcrumb)) {
        $candidate = $CandidateByBreadcrumb[$SourceBreadcrumb]
        if ([string]::Equals($candidate.Mode, "Wrapped", [System.StringComparison]::Ordinal)) {
            $normalized = ConvertTo-SplitOpenApiMultiValueTypeEnumValue `
                -Value $Value `
                -Context Schema `
                -SourceBreadcrumb $SourceBreadcrumb `
                -DestinationBreadcrumb $DestinationBreadcrumb `
                -CandidateByBreadcrumb $CandidateByBreadcrumb `
                -Relocations $Relocations `
                -SuppressCurrentCandidate `
                -SuppressRelocations `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
            return [ordered]@{
                oneOf = [object[]](New-OpenApiMultiValueTypeEnumVariants `
                    -Schema $normalized `
                    -Values $candidate.Values)
            }
        }
    }

    $result = [ordered]@{}
    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $token = ConvertTo-JsonPointerToken -Token $property.Name
        $sourceChildBreadcrumb = "$SourceBreadcrumb/$token"
        $destinationChildBreadcrumb = "$DestinationBreadcrumb/$token"
        if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal) -and
            $property.Name -in @("oneOf", "anyOf") -and
            (Test-JsonArrayValue -Value $property.Value)) {
            $branches = [System.Collections.Generic.List[object]]::new()
            for ($index = 0; $index -lt $property.Value.Count; $index++) {
                $branchSourceBreadcrumb = "$sourceChildBreadcrumb/$index"
                $branchDestinationBreadcrumb = "$destinationChildBreadcrumb/$($branches.Count)"
                if ($CandidateByBreadcrumb.ContainsKey($branchSourceBreadcrumb) -and
                    $CandidateByBreadcrumb[$branchSourceBreadcrumb].Mode -ceq "Expanded") {
                    $candidate = $CandidateByBreadcrumb[$branchSourceBreadcrumb]
                    $normalized = ConvertTo-SplitOpenApiMultiValueTypeEnumValue `
                        -Value $property.Value[$index] `
                        -Context Schema `
                        -SourceBreadcrumb $branchSourceBreadcrumb `
                        -DestinationBreadcrumb $branchDestinationBreadcrumb `
                        -CandidateByBreadcrumb $CandidateByBreadcrumb `
                        -Relocations $Relocations `
                        -SuppressCurrentCandidate `
                        -SuppressRelocations `
                        -Depth ($Depth + 1) `
                        -MaximumDepth $MaximumDepth
                    foreach ($variant in (New-OpenApiMultiValueTypeEnumVariants `
                        -Schema $normalized `
                        -Values $candidate.Values)) {
                        $branches.Add($variant)
                    }
                    continue
                }

                if (-not $SuppressRelocations) {
                    Add-OpenApiMultiValueTypeEnumPointerRelocation `
                        -Relocations $Relocations `
                        -SourcePrefix $branchSourceBreadcrumb `
                        -DestinationPrefix $branchDestinationBreadcrumb
                }
                $branches.Add((ConvertTo-SplitOpenApiMultiValueTypeEnumValue `
                    -Value $property.Value[$index] `
                    -Context Schema `
                    -SourceBreadcrumb $branchSourceBreadcrumb `
                    -DestinationBreadcrumb $branchDestinationBreadcrumb `
                    -CandidateByBreadcrumb $CandidateByBreadcrumb `
                    -Relocations $Relocations `
                    -SuppressRelocations:$SuppressRelocations `
                    -Depth ($Depth + 1) `
                    -MaximumDepth $MaximumDepth))
            }
            $result[$property.Name] = [object[]]$branches.ToArray()
            continue
        }

        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        $result[$property.Name] = ConvertTo-SplitOpenApiMultiValueTypeEnumValue `
            -Value $property.Value `
            -Context $childContext `
            -SourceBreadcrumb $sourceChildBreadcrumb `
            -DestinationBreadcrumb $destinationChildBreadcrumb `
            -CandidateByBreadcrumb $CandidateByBreadcrumb `
            -Relocations $Relocations `
            -SuppressRelocations:$SuppressRelocations `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
    return $result
}

function Assert-NoSplittableOpenApiMultiValueTypeEnums {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Document
    )

    $candidates = [System.Collections.Generic.List[object]]::new()
    Add-OpenApiMultiValueTypeEnumSplitCandidates `
        -Value $Document `
        -Context OpenApi `
        -Breadcrumb "#" `
        -Candidates $candidates
    if ($candidates.Count -gt 0) {
        throw "Split output retained eligible multi-value type enum at '$($candidates[0].Breadcrumb)/properties/type/enum'."
    }
}

function ConvertTo-SplitOpenApiMultiValueTypeEnumDocument {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Document
    )

    $candidates = [System.Collections.Generic.List[object]]::new()
    Add-OpenApiMultiValueTypeEnumSplitCandidates `
        -Value $Document `
        -Context OpenApi `
        -Breadcrumb "#" `
        -Candidates $candidates
    Assert-OpenApiMultiValueTypeEnumSplitReferencesAreSafe `
        -Document $Document `
        -Candidates ([object[]]$candidates.ToArray())

    $candidateByBreadcrumb = [System.Collections.Generic.Dictionary[string, object]]::new(
        [System.StringComparer]::Ordinal
    )
    foreach ($candidate in $candidates) {
        $candidateByBreadcrumb[$candidate.Breadcrumb] = $candidate
    }
    $relocations = [System.Collections.Generic.Dictionary[string, string]]::new(
        [System.StringComparer]::Ordinal
    )
    $split = ConvertTo-SplitOpenApiMultiValueTypeEnumValue `
        -Value $Document `
        -Context OpenApi `
        -SourceBreadcrumb "#" `
        -DestinationBreadcrumb "#" `
        -CandidateByBreadcrumb $candidateByBreadcrumb `
        -Relocations $relocations
    $relocated = ConvertTo-RelocatedOpenApiPointers `
        -Value $split `
        -Relocations $relocations

    Assert-OpenApiReferencesResolve -Document $relocated
    Assert-AdditionalOpenApiReferencesResolve -Document $relocated
    Assert-NoSplittableOpenApiMultiValueTypeEnums -Document $relocated

    $generatedVariantCount = 0
    foreach ($candidate in $candidates) {
        $generatedVariantCount += $candidate.Values.Count
    }
    return [PSCustomObject]@{
        Document = $relocated
        SplitSchemaCount = $candidates.Count
        GeneratedVariantCount = $generatedVariantCount
        ExpandedCompositionBranchCount = @($candidates | Where-Object Mode -ceq "Expanded").Count
        WrappedSchemaCount = @($candidates | Where-Object Mode -ceq "Wrapped").Count
        RelocationCount = $relocations.Count
    }
}

function Get-DefaultSplitOpenApiMultiValueTypeEnumPath {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath
    )

    $fullInputPath = [System.IO.Path]::GetFullPath($InputPath)
    $directory = [System.IO.Path]::GetDirectoryName($fullInputPath)
    $fileName = [System.IO.Path]::GetFileName($fullInputPath)
    if ($fileName.EndsWith(".type-enum-split.openapi.json", [System.StringComparison]::OrdinalIgnoreCase) -or
        $fileName.EndsWith(".type-enum-split.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        return $fullInputPath
    }
    if ($fileName.EndsWith(".openapi.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $baseName = $fileName.Substring(0, $fileName.Length - ".openapi.json".Length)
        return Join-Path $directory "$baseName.type-enum-split.openapi.json"
    }
    if ($fileName.EndsWith(".json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $baseName = $fileName.Substring(0, $fileName.Length - ".json".Length)
        return Join-Path $directory "$baseName.type-enum-split.json"
    }
    return Join-Path $directory "$fileName.type-enum-split.json"
}

function Invoke-OpenApiMultiValueTypeEnumSplitter {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath,

        [Parameter()]
        [string]$OutputPath
    )

    $resolvedInputPath = (Resolve-Path -LiteralPath $InputPath -ErrorAction Stop).ProviderPath
    if (-not [System.IO.File]::Exists($resolvedInputPath)) {
        throw "The OpenAPI input path is not a file: $resolvedInputPath"
    }
    if ([string]::IsNullOrWhiteSpace($OutputPath)) {
        $OutputPath = Get-DefaultSplitOpenApiMultiValueTypeEnumPath -InputPath $resolvedInputPath
    }
    else {
        $OutputPath = [System.IO.Path]::GetFullPath($OutputPath)
    }

    $document = Read-OpenApiDocument -Path $resolvedInputPath
    $result = ConvertTo-SplitOpenApiMultiValueTypeEnumDocument -Document $document
    $writtenPath = Write-OpenApiJsonFile -Document $result.Document -Path $OutputPath

    Write-Host ""
    Write-Host "Input: $resolvedInputPath"
    Write-Host "Output: $writtenPath"
    Write-Host "Schemas split: $($result.SplitSchemaCount)"
    Write-Host "Singleton variants generated: $($result.GeneratedVariantCount)"
    Write-Host "Composition branches expanded: $($result.ExpandedCompositionBranchCount)"
    Write-Host "Schemas wrapped: $($result.WrappedSchemaCount)"
    Write-Host "JSON Pointer prefixes relocated: $($result.RelocationCount)"

    return $result
}

