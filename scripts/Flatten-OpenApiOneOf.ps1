. $helperPath

function Get-OpenApiDiscriminatorPropertyName {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Schema
    )

    $discriminator = Get-JsonPropertyValue -Object $Schema -Name "discriminator"
    if (-not (Test-JsonObjectValue -Value $discriminator)) {
        return $null
    }

    $propertyName = Get-JsonPropertyValue -Object $discriminator -Name "propertyName"
    if ($propertyName -isnot [string] -or [string]::IsNullOrWhiteSpace($propertyName)) {
        return $null
    }

    return $propertyName
}

function Get-FlattenableOpenApiOneOfWrapper {
    param(
        [Parameter(Mandatory = $true)]
        [object]$ParentSchema,

        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$WrapperSchema,

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "nested oneOf eligibility exceeds the supported depth of $MaximumDepth."
    }
    if (-not (Test-JsonObjectValue -Value $ParentSchema) -or
        -not (Test-JsonObjectValue -Value $WrapperSchema)) {
        return $null
    }

    if (Test-JsonProperty -Object $ParentSchema -Name "type") {
        $parentType = Get-JsonPropertyValue -Object $ParentSchema -Name "type"
        if ($parentType -isnot [string] -or
            -not [string]::Equals($parentType, "object", [System.StringComparison]::Ordinal)) {
            return $null
        }
    }

    $propertyName = Get-OpenApiDiscriminatorPropertyName -Schema $ParentSchema
    if ($null -eq $propertyName) {
        return $null
    }

    $plan = Get-OpenApiInlineDiscriminatorUnionPlan `
        -Schema $ParentSchema `
        -PropertyName $propertyName `
        -Breadcrumb "#" `
        -RequireDiscriminator `
        -Depth $Depth `
        -MaximumDepth $MaximumDepth
    if ($null -eq $plan) {
        return $null
    }

    foreach ($branchPlan in $plan.BranchPlans) {
        if ([object]::ReferenceEquals($branchPlan.Branch, $WrapperSchema) -and
            [string]::Equals($branchPlan.Kind, "Wrapper", [System.StringComparison]::Ordinal)) {
            return [PSCustomObject]@{
                PropertyName = $propertyName
                Branches = $branchPlan.NestedPlan.Branches
                Values = $branchPlan.Values
            }
        }
    }
    return $null
}

function Add-DirectOpenApiPointerRelocation {
    param(
        [Parameter(Mandatory = $true)]
        [System.Collections.Generic.Dictionary[string, string]]$Relocations,

        [Parameter(Mandatory = $true)]
        [string]$SourcePrefix,

        [Parameter(Mandatory = $true)]
        [string]$DestinationPrefix
    )

    if ([string]::Equals($SourcePrefix, $DestinationPrefix, [System.StringComparison]::Ordinal)) {
        return
    }
    Add-OpenApiPointerRelocation `
        -Relocations $Relocations `
        -SourcePrefix $SourcePrefix `
        -DestinationPrefix $DestinationPrefix
}

function Get-DirectlyRelocatedOpenApiPointer {
    param(
        [Parameter(Mandatory = $true)]
        [string]$Pointer,

        [Parameter(Mandatory = $true)]
        [System.Collections.Generic.Dictionary[string, string]]$Relocations
    )

    if (-not $Pointer.StartsWith("#", [System.StringComparison]::Ordinal) -or
        [string]::Equals($Pointer, "#", [System.StringComparison]::Ordinal)) {
        return $Pointer
    }

    $canonicalPointer = Get-CanonicalJsonPointer -Pointer $Pointer
    $matchingPrefix = $null
    foreach ($sourcePrefix in $Relocations.Keys) {
        if (($canonicalPointer.Length -eq $sourcePrefix.Length -or
            ($canonicalPointer.Length -gt $sourcePrefix.Length -and $canonicalPointer[$sourcePrefix.Length] -eq '/')) -and
            $canonicalPointer.StartsWith($sourcePrefix, [System.StringComparison]::Ordinal) -and
            ($null -eq $matchingPrefix -or $sourcePrefix.Length -gt $matchingPrefix.Length)) {
            $matchingPrefix = $sourcePrefix
        }
    }

    if ($null -eq $matchingPrefix) {
        return $Pointer
    }
    return $Relocations[$matchingPrefix] + $canonicalPointer.Substring($matchingPrefix.Length)
}

function ConvertTo-DirectlyRelocatedOpenApiPointers {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter(Mandatory = $true)]
        [System.Collections.Generic.Dictionary[string, string]]$Relocations,

        [Parameter()]
        [ValidateSet("Default", "Discriminator", "Mapping")]
        [string]$Context = "Default",

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "oneOf pointer relocation exceeds the supported depth of $MaximumDepth."
    }
    if ($null -eq $Value) {
        return $null
    }
    if (Test-JsonArrayValue -Value $Value) {
        [object[]]$items = [object[]]::new($Value.Count)
        for ($index = 0; $index -lt $Value.Count; $index++) {
            $items[$index] = ConvertTo-DirectlyRelocatedOpenApiPointers `
                -Value $Value[$index] `
                -Relocations $Relocations `
                -Context Default `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return ,$items
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return $Value
    }

    $result = [ordered]@{}
    foreach ($property in (Get-JsonProperties -Value $Value)) {
        if ([string]::Equals($Context, "Mapping", [System.StringComparison]::Ordinal) -and
            $property.Value -is [string]) {
            $result[$property.Name] = Get-DirectlyRelocatedOpenApiPointer `
                -Pointer $property.Value `
                -Relocations $Relocations
            continue
        }
        if (@('$ref', '$dynamicRef', '$recursiveRef') -ccontains $property.Name -and
            $property.Value -is [string]) {
            $result[$property.Name] = Get-DirectlyRelocatedOpenApiPointer `
                -Pointer $property.Value `
                -Relocations $Relocations
            continue
        }

        $childContext = "Default"
        if ([string]::Equals($Context, "Default", [System.StringComparison]::Ordinal) -and
            [string]::Equals($property.Name, "discriminator", [System.StringComparison]::Ordinal)) {
            $childContext = "Discriminator"
        }
        elseif ([string]::Equals($Context, "Discriminator", [System.StringComparison]::Ordinal) -and
            [string]::Equals($property.Name, "mapping", [System.StringComparison]::Ordinal)) {
            $childContext = "Mapping"
        }

        $result[$property.Name] = ConvertTo-DirectlyRelocatedOpenApiPointers `
            -Value $property.Value `
            -Relocations $Relocations `
            -Context $childContext `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
    return $result
}

function Assert-NoRemovedOpenApiOneOfTargets {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [System.Collections.Generic.HashSet[string]]$RemovedPointers,

        [Parameter()]
        [ValidateSet("Default", "Discriminator", "Mapping")]
        [string]$Context = "Default",

        [Parameter()]
        [string]$Breadcrumb = "#"
    )

    if ($null -eq $Value) {
        return
    }
    if (Test-JsonArrayValue -Value $Value) {
        for ($index = 0; $index -lt $Value.Count; $index++) {
            Assert-NoRemovedOpenApiOneOfTargets `
                -Value $Value[$index] `
                -RemovedPointers $RemovedPointers `
                -Context Default `
                -Breadcrumb "$Breadcrumb/$index"
        }
        return
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return
    }

    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $propertyBreadcrumb = "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)"
        $isMappingValue = [string]::Equals($Context, "Mapping", [System.StringComparison]::Ordinal) -and
            $property.Value -is [string]
        $isReferenceValue = @('$ref', '$dynamicRef', '$recursiveRef') -ccontains $property.Name -and
            $property.Value -is [string]
        if ($isMappingValue -or $isReferenceValue) {
            $target = $property.Value
            $canonicalTarget = if ($target.StartsWith("#", [System.StringComparison]::Ordinal)) {
                Get-CanonicalJsonPointer -Pointer $target
            }
            else {
                $target
            }
            if ($RemovedPointers.Contains($canonicalTarget)) {
                throw "Cannot flatten nested oneOf because the reference at '$propertyBreadcrumb' targets removed wrapper location '$target'."
            }
        }

        $childContext = "Default"
        if ([string]::Equals($Context, "Default", [System.StringComparison]::Ordinal) -and
            [string]::Equals($property.Name, "discriminator", [System.StringComparison]::Ordinal)) {
            $childContext = "Discriminator"
        }
        elseif ([string]::Equals($Context, "Discriminator", [System.StringComparison]::Ordinal) -and
            [string]::Equals($property.Name, "mapping", [System.StringComparison]::Ordinal)) {
            $childContext = "Mapping"
        }

        Assert-NoRemovedOpenApiOneOfTargets `
            -Value $property.Value `
            -RemovedPointers $RemovedPointers `
            -Context $childContext `
            -Breadcrumb $propertyBreadcrumb
    }
}

function Add-FlattenedOpenApiOneOfBranch {
    param(
        [Parameter(Mandatory = $true)]
        [object]$ParentSchema,

        [Parameter(Mandatory = $true)]
        [string]$RetainedParentDestinationBreadcrumb,

        [Parameter(Mandatory = $true)]
        [object]$Branch,

        [Parameter(Mandatory = $true)]
        [string]$BranchSourceBreadcrumb,

        [Parameter(Mandatory = $true)]
        [string]$DestinationOneOfBreadcrumb,

        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [System.Collections.Generic.List[object]]$OutputBranches,

        [Parameter(Mandatory = $true)]
        [System.Collections.Generic.Dictionary[string, string]]$Relocations,

        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [System.Collections.Generic.HashSet[string]]$RemovedPointers,

        [Parameter(Mandatory = $true)]
        [ref]$FlattenedOneOfCount,

        [Parameter(Mandatory = $true)]
        [ref]$PromotedBranchCount,

        [Parameter(Mandatory = $true)]
        [int]$Depth,

        [Parameter(Mandatory = $true)]
        [int]$MaximumDepth
    )

    $candidate = Get-FlattenableOpenApiOneOfWrapper `
        -ParentSchema $ParentSchema `
        -WrapperSchema $Branch `
        -MaximumDepth $MaximumDepth
    if ($null -eq $candidate) {
        $destinationBreadcrumb = "$DestinationOneOfBreadcrumb/$($OutputBranches.Count)"
        Add-DirectOpenApiPointerRelocation `
            -Relocations $Relocations `
            -SourcePrefix $BranchSourceBreadcrumb `
            -DestinationPrefix $destinationBreadcrumb
        $OutputBranches.Add((ConvertTo-FlattenedOpenApiOneOfValue `
            -Value $Branch `
            -Context Schema `
            -SourceBreadcrumb $BranchSourceBreadcrumb `
            -DestinationBreadcrumb $destinationBreadcrumb `
            -Relocations $Relocations `
            -RemovedPointers $RemovedPointers `
            -FlattenedOneOfCount $FlattenedOneOfCount `
            -PromotedBranchCount $PromotedBranchCount `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth))
        return
    }

    $FlattenedOneOfCount.Value++
    $PromotedBranchCount.Value += $candidate.Branches.Count
    $null = $RemovedPointers.Add($BranchSourceBreadcrumb)
    $null = $RemovedPointers.Add("$BranchSourceBreadcrumb/oneOf")

    foreach ($property in (Get-JsonProperties -Value $Branch)) {
        if ([string]::Equals($property.Name, "oneOf", [System.StringComparison]::Ordinal)) {
            continue
        }
        $token = ConvertTo-JsonPointerToken -Token $property.Name
        $sourcePrefix = "$BranchSourceBreadcrumb/$token"
        if (Test-JsonProperty -Object $ParentSchema -Name $property.Name) {
            Add-DirectOpenApiPointerRelocation `
                -Relocations $Relocations `
                -SourcePrefix $sourcePrefix `
                -DestinationPrefix "$RetainedParentDestinationBreadcrumb/$token"
        }
        else {
            $null = $RemovedPointers.Add($sourcePrefix)
        }
    }

    for ($index = 0; $index -lt $candidate.Branches.Count; $index++) {
        Add-FlattenedOpenApiOneOfBranch `
            -ParentSchema $Branch `
            -RetainedParentDestinationBreadcrumb $RetainedParentDestinationBreadcrumb `
            -Branch $candidate.Branches[$index] `
            -BranchSourceBreadcrumb "$BranchSourceBreadcrumb/oneOf/$index" `
            -DestinationOneOfBreadcrumb $DestinationOneOfBreadcrumb `
            -OutputBranches $OutputBranches `
            -Relocations $Relocations `
            -RemovedPointers $RemovedPointers `
            -FlattenedOneOfCount $FlattenedOneOfCount `
            -PromotedBranchCount $PromotedBranchCount `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
}

function ConvertTo-FlattenedOpenApiOneOfValue {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter(Mandatory = $true)]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context,

        [Parameter(Mandatory = $true)]
        [string]$SourceBreadcrumb,

        [Parameter(Mandatory = $true)]
        [string]$DestinationBreadcrumb,

        [Parameter(Mandatory = $true)]
        [System.Collections.Generic.Dictionary[string, string]]$Relocations,

        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [System.Collections.Generic.HashSet[string]]$RemovedPointers,

        [Parameter(Mandatory = $true)]
        [ref]$FlattenedOneOfCount,

        [Parameter(Mandatory = $true)]
        [ref]$PromotedBranchCount,

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "oneOf flattening exceeds the supported depth of $MaximumDepth at '$SourceBreadcrumb'."
    }
    if ($null -eq $Value) {
        return $null
    }
    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        [object[]]$items = [object[]]::new($Value.Count)
        for ($index = 0; $index -lt $Value.Count; $index++) {
            $items[$index] = ConvertTo-FlattenedOpenApiOneOfValue `
                -Value $Value[$index] `
                -Context $itemContext `
                -SourceBreadcrumb "$SourceBreadcrumb/$index" `
                -DestinationBreadcrumb "$DestinationBreadcrumb/$index" `
                -Relocations $Relocations `
                -RemovedPointers $RemovedPointers `
                -FlattenedOneOfCount $FlattenedOneOfCount `
                -PromotedBranchCount $PromotedBranchCount `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return ,$items
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return $Value
    }
    if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
        $Context = "Schema"
    }

    $isSchema = [string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal)
    $oneOf = if ($isSchema) { Get-JsonPropertyValue -Object $Value -Name "oneOf" } else { $null }
    $hasFlattenableWrapper = $false
    if (Test-JsonArrayValue -Value $oneOf) {
        foreach ($branch in $oneOf) {
            if ($null -ne (Get-FlattenableOpenApiOneOfWrapper `
                -ParentSchema $Value `
                -WrapperSchema $branch `
                -MaximumDepth $MaximumDepth)) {
                $hasFlattenableWrapper = $true
                break
            }
        }
    }

    $result = [ordered]@{}
    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $token = ConvertTo-JsonPointerToken -Token $property.Name
        $sourceChildBreadcrumb = "$SourceBreadcrumb/$token"
        $destinationChildBreadcrumb = "$DestinationBreadcrumb/$token"
        if ($hasFlattenableWrapper -and
            [string]::Equals($property.Name, "oneOf", [System.StringComparison]::Ordinal)) {
            $branches = [System.Collections.Generic.List[object]]::new()
            for ($index = 0; $index -lt $oneOf.Count; $index++) {
                Add-FlattenedOpenApiOneOfBranch `
                    -ParentSchema $Value `
                    -RetainedParentDestinationBreadcrumb $DestinationBreadcrumb `
                    -Branch $oneOf[$index] `
                    -BranchSourceBreadcrumb "$sourceChildBreadcrumb/$index" `
                    -DestinationOneOfBreadcrumb $destinationChildBreadcrumb `
                    -OutputBranches $branches `
                    -Relocations $Relocations `
                    -RemovedPointers $RemovedPointers `
                    -FlattenedOneOfCount $FlattenedOneOfCount `
                    -PromotedBranchCount $PromotedBranchCount `
                    -Depth ($Depth + 1) `
                    -MaximumDepth $MaximumDepth
            }
            $result[$property.Name] = @($branches)
            continue
        }

        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        $result[$property.Name] = ConvertTo-FlattenedOpenApiOneOfValue `
            -Value $property.Value `
            -Context $childContext `
            -SourceBreadcrumb $sourceChildBreadcrumb `
            -DestinationBreadcrumb $destinationChildBreadcrumb `
            -Relocations $Relocations `
            -RemovedPointers $RemovedPointers `
            -FlattenedOneOfCount $FlattenedOneOfCount `
            -PromotedBranchCount $PromotedBranchCount `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
    return $result
}

function Assert-NoFlattenableOpenApiOneOf {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter()]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context = "OpenApi",

        [Parameter()]
        [string]$Breadcrumb = "#",

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "oneOf flattening postcondition exceeds the supported depth of $MaximumDepth at '$Breadcrumb'."
    }
    if ($null -eq $Value) {
        return
    }
    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        for ($index = 0; $index -lt $Value.Count; $index++) {
            Assert-NoFlattenableOpenApiOneOf `
                -Value $Value[$index] `
                -Context $itemContext `
                -Breadcrumb "$Breadcrumb/$index" `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return
    }
    if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
        $Context = "Schema"
    }

    if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal)) {
        $oneOf = Get-JsonPropertyValue -Object $Value -Name "oneOf"
        if (Test-JsonArrayValue -Value $oneOf) {
            for ($index = 0; $index -lt $oneOf.Count; $index++) {
                if ($null -ne (Get-FlattenableOpenApiOneOfWrapper `
                    -ParentSchema $Value `
                    -WrapperSchema $oneOf[$index] `
                    -MaximumDepth $MaximumDepth)) {
                    throw "Flattened output retained a matching nested oneOf wrapper at '$Breadcrumb/oneOf/$index'."
                }
            }
        }
    }

    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        Assert-NoFlattenableOpenApiOneOf `
            -Value $property.Value `
            -Context $childContext `
            -Breadcrumb "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)" `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
}

function ConvertTo-FlattenedOpenApiOneOfDocument {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Document
    )

    $relocations = [System.Collections.Generic.Dictionary[string, string]]::new(
        [System.StringComparer]::Ordinal
    )
    $removedPointers = [System.Collections.Generic.HashSet[string]]::new(
        [System.StringComparer]::Ordinal
    )
    $flattenedOneOfCount = 0
    $promotedBranchCount = 0
    $flattened = ConvertTo-FlattenedOpenApiOneOfValue `
        -Value $Document `
        -Context OpenApi `
        -SourceBreadcrumb "#" `
        -DestinationBreadcrumb "#" `
        -Relocations $relocations `
        -RemovedPointers $removedPointers `
        -FlattenedOneOfCount ([ref]$flattenedOneOfCount) `
        -PromotedBranchCount ([ref]$promotedBranchCount)

    Assert-NoRemovedOpenApiOneOfTargets `
        -Value $Document `
        -RemovedPointers $removedPointers
    $relocated = ConvertTo-DirectlyRelocatedOpenApiPointers `
        -Value $flattened `
        -Relocations $relocations
    Assert-OpenApiReferencesResolve -Document $relocated
    Assert-AdditionalOpenApiReferencesResolve -Document $relocated
    Assert-NoFlattenableOpenApiOneOf -Value $relocated

    return [PSCustomObject]@{
        Document = $relocated
        FlattenedOneOfCount = $flattenedOneOfCount
        PromotedBranchCount = $promotedBranchCount
        RelocationCount = $relocations.Count
    }
}

function Get-DefaultFlattenedOpenApiOneOfPath {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath
    )

    $fullInputPath = [System.IO.Path]::GetFullPath($InputPath)
    $directory = [System.IO.Path]::GetDirectoryName($fullInputPath)
    $fileName = [System.IO.Path]::GetFileName($fullInputPath)
    if ($fileName.EndsWith(".oneof-flattened.openapi.json", [System.StringComparison]::OrdinalIgnoreCase) -or
        $fileName.EndsWith(".oneof-flattened.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        return $fullInputPath
    }
    if ($fileName.EndsWith(".openapi.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $baseName = $fileName.Substring(0, $fileName.Length - ".openapi.json".Length)
        return Join-Path $directory "$baseName.oneof-flattened.openapi.json"
    }
    if ($fileName.EndsWith(".json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $baseName = $fileName.Substring(0, $fileName.Length - ".json".Length)
        return Join-Path $directory "$baseName.oneof-flattened.json"
    }
    return Join-Path $directory "$fileName.oneof-flattened.json"
}

function Invoke-OpenApiOneOfFlattener {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath,

        [Parameter()]
        [string]$OutputPath
    )

    $resolvedInputPath = (Resolve-Path -LiteralPath $InputPath -ErrorAction Stop).ProviderPath
    if (-not [System.IO.File]::Exists($resolvedInputPath)) {
        throw "The OpenAPI input path is not a file: $resolvedInputPath"
    }
    if ([string]::IsNullOrWhiteSpace($OutputPath)) {
        $OutputPath = Get-DefaultFlattenedOpenApiOneOfPath -InputPath $resolvedInputPath
    }
    else {
        $OutputPath = [System.IO.Path]::GetFullPath($OutputPath)
    }

    $document = Read-OpenApiDocument -Path $resolvedInputPath
    $result = ConvertTo-FlattenedOpenApiOneOfDocument -Document $document
    $writtenPath = Write-OpenApiJsonFile -Document $result.Document -Path $OutputPath

    Write-Host ""
    Write-Host "Input: $resolvedInputPath"
    Write-Host "Output: $writtenPath"
    Write-Host "Nested oneOf wrappers flattened: $($result.FlattenedOneOfCount)"
    Write-Host "oneOf branches promoted: $($result.PromotedBranchCount)"
    Write-Host "JSON Pointer prefixes relocated: $($result.RelocationCount)"

    return $result
}

