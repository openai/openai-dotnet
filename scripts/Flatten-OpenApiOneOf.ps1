<#
.SYNOPSIS
    Flattens matching nested oneOf schema wrappers in an OpenAPI document.

.DESCRIPTION
    Replaces a direct oneOf branch with its inner oneOf branches when the parent
    and wrapper use the same discriminator property and any additional siblings
    beyond type, discriminator, and oneOf are deeply equal. Discriminator mapping
    differences are ignored because final mappings are rebuilt after components
    receive stable names. Matching ordinary constraints remain once on the
    parent. Location-sensitive identifiers, anchors, and extension properties
    make a wrapper ineligible.

    Every recursive leaf must require the discriminator property with finite
    string const/enum values, and accepted values must be globally disjoint. The
    transparent nested wrappers may omit type when those leaves are explicit
    objects. The transformation preserves encounter order, relocates affected
    local JSON pointers, and writes a separate oneOf-flattened document. Run
    Wrap-OpenApiSingletonTypeEnums.ps1 and then Sort-OpenApiDocument.ps1
    afterward to produce canonical ordering.

.PARAMETER InputPath
    The normalized OpenAPI JSON document to flatten.

.PARAMETER OutputPath
    The destination JSON file. When omitted, a sibling filename is generated by
    inserting '.oneof-flattened' before '.openapi.json' or the final '.json'
    suffix. If the input already has that suffix, it is atomically rewritten in
    place.

.EXAMPLE
    ./scripts/Flatten-OpenApiOneOf.ps1 `
        ./artifacts/openapi-extracts/responses.inlined.flattened.simplified.recursive-simplified.type-enum-split.oneof-discriminated.oneof-normalized.openapi.json
    ./scripts/Wrap-OpenApiSingletonTypeEnums.ps1 `
        ./artifacts/openapi-extracts/responses.inlined.flattened.simplified.recursive-simplified.type-enum-split.oneof-discriminated.oneof-normalized.oneof-flattened.openapi.json
    ./scripts/Sort-OpenApiDocument.ps1 `
        ./artifacts/openapi-extracts/responses.inlined.flattened.simplified.recursive-simplified.type-enum-split.oneof-discriminated.oneof-normalized.oneof-flattened.singleton-type-wrapped.openapi.json
#>

#Requires -Version 7.0

[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string]$InputPath,

    [Parameter()]
    [string]$OutputPath
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$helperPath = Join-Path $PSScriptRoot "_OpenApiDocument.Helpers.ps1"
if (-not (Test-Path -LiteralPath $helperPath -PathType Leaf)) {
