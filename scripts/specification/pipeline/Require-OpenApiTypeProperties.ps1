<#
.SYNOPSIS
    Requires the type property on explicit object schemas that declare it.

.DESCRIPTION
    Traverses OpenAPI Schema Objects and ensures every exact `type: "object"`
    schema with an exact `properties.type` entry also lists `type` in its
    required array. Existing required names and object member order are
    preserved. Schema-like literal values are ignored.

.PARAMETER InputPath
    The OpenAPI JSON document to transform.

.PARAMETER OutputPath
    The destination JSON file. When omitted, a sibling filename is generated by
    inserting '.type-properties-required' before the OpenAPI JSON suffix.

.EXAMPLE
    ./scripts/specification/pipeline/Require-OpenApiTypeProperties.ps1 `
        ./artifacts/custom.openapi.json `
        -OutputPath ./artifacts/custom.type-properties-required.openapi.json
#>

#Requires -Version 7.0

[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string]$InputPath,

    [Parameter()]
    [string]$OutputPath
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$helperPath = Join-Path $PSScriptRoot "_OpenApiDocument.Helpers.ps1"
if (-not (Test-Path -LiteralPath $helperPath -PathType Leaf)) {
    throw "The shared OpenAPI helper script was not found: $helperPath"
}
. $helperPath

function Get-OpenApiRequiredTypePropertyPlan {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Schema,

        [Parameter(Mandatory = $true)]
        [string]$Breadcrumb
    )

    if (-not (Test-JsonObjectValue -Value $Schema)) {
        return $null
    }
    $schemaType = Get-JsonPropertyValue -Object $Schema -Name "type"
    if ($schemaType -isnot [string] -or
        -not [string]::Equals($schemaType, "object", [System.StringComparison]::Ordinal)) {
        return $null
    }
    $properties = Get-JsonPropertyValue -Object $Schema -Name "properties"
    if (-not (Test-JsonObjectValue -Value $properties) -or
        -not (Test-JsonProperty -Object $properties -Name "type")) {
        return $null
    }

    if (-not (Test-JsonProperty -Object $Schema -Name "required")) {
        return [PSCustomObject]@{
            HasRequired = $false
            IsChanged = $true
            RequiredNames = [object[]]@("type")
        }
    }

    $required = Get-JsonPropertyValue -Object $Schema -Name "required"
    if (-not (Test-JsonArrayValue -Value $required)) {
        throw "The required keyword at '$Breadcrumb/required' must be an array."
    }
    $containsType = $false
    [object[]]$requiredNames = @($required)
    for ($index = 0; $index -lt $requiredNames.Count; $index++) {
        $requiredName = $requiredNames[$index]
        if ($requiredName -isnot [string]) {
            throw "Every required name at '$Breadcrumb/required' must be a string; item $index is invalid."
        }
        if ([string]::Equals($requiredName, "type", [System.StringComparison]::Ordinal)) {
            $containsType = $true
        }
    }

    return [PSCustomObject]@{
        HasRequired = $true
        IsChanged = -not $containsType
        RequiredNames = if ($containsType) {
            $requiredNames
        }
        else {
            [object[]]@($requiredNames + "type")
        }
    }
}

function ConvertTo-OpenApiRequiredTypePropertiesValue {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter(Mandatory = $true)]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context,

        [Parameter(Mandatory = $true)]
        [string]$Breadcrumb,

        [Parameter(Mandatory = $true)]
        [ref]$RequiredTypePropertyCount,

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "Type-property requirement exceeds the supported depth of $MaximumDepth at '$Breadcrumb'."
    }
    if ($null -eq $Value) {
        return $null
    }
    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        [object[]]$items = [object[]]::new($Value.Count)
        for ($index = 0; $index -lt $Value.Count; $index++) {
            $items[$index] = ConvertTo-OpenApiRequiredTypePropertiesValue `
                -Value $Value[$index] `
                -Context $itemContext `
                -Breadcrumb "$Breadcrumb/$index" `
                -RequiredTypePropertyCount $RequiredTypePropertyCount `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return ,$items
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return $Value
    }

    $plan = if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal)) {
        Get-OpenApiRequiredTypePropertyPlan -Schema $Value -Breadcrumb $Breadcrumb
    }
    else {
        $null
    }

    $result = [ordered]@{}
    foreach ($property in (Get-JsonProperties -Value $Value)) {
        if ($null -ne $plan -and $plan.IsChanged) {
            if (-not $plan.HasRequired -and
                [string]::Equals($property.Name, "properties", [System.StringComparison]::Ordinal)) {
                $result["required"] = [object[]]$plan.RequiredNames
                $RequiredTypePropertyCount.Value++
            }
            elseif ($plan.HasRequired -and
                [string]::Equals($property.Name, "required", [System.StringComparison]::Ordinal)) {
                $result[$property.Name] = [object[]]$plan.RequiredNames
                $RequiredTypePropertyCount.Value++
                continue
            }
        }

        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        $result[$property.Name] = ConvertTo-OpenApiRequiredTypePropertiesValue `
            -Value $property.Value `
            -Context $childContext `
            -Breadcrumb "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)" `
            -RequiredTypePropertyCount $RequiredTypePropertyCount `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
    return $result
}

function Assert-OpenApiTypePropertiesRequired {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter()]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context = "OpenApi",

        [Parameter()]
        [string]$Breadcrumb = "#",

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "Type-property requirement postcondition exceeds the supported depth of $MaximumDepth at '$Breadcrumb'."
    }
    if ($null -eq $Value) {
        return
    }
    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        for ($index = 0; $index -lt $Value.Count; $index++) {
            Assert-OpenApiTypePropertiesRequired `
                -Value $Value[$index] `
                -Context $itemContext `
                -Breadcrumb "$Breadcrumb/$index" `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return
    }

    if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal)) {
        $plan = Get-OpenApiRequiredTypePropertyPlan -Schema $Value -Breadcrumb $Breadcrumb
        if ($null -ne $plan -and $plan.IsChanged) {
            throw "Object schema at '$Breadcrumb' declares properties.type but does not require 'type'."
        }
    }

    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        Assert-OpenApiTypePropertiesRequired `
            -Value $property.Value `
            -Context $childContext `
            -Breadcrumb "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)" `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
}

function ConvertTo-OpenApiRequiredTypePropertiesDocument {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Document
    )

    $requiredTypePropertyCount = 0
    $converted = ConvertTo-OpenApiRequiredTypePropertiesValue `
        -Value $Document `
        -Context OpenApi `
        -Breadcrumb "#" `
        -RequiredTypePropertyCount ([ref]$requiredTypePropertyCount)
    Assert-OpenApiTypePropertiesRequired -Value $converted
    Assert-OpenApiReferencesResolve -Document $converted
    Assert-AdditionalOpenApiReferencesResolve -Document $converted

    return [PSCustomObject]@{
        Document = $converted
        RequiredTypePropertyCount = $requiredTypePropertyCount
    }
}

function Get-DefaultRequiredTypePropertiesOpenApiPath {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath
    )

    $fullInputPath = [System.IO.Path]::GetFullPath($InputPath)
    $directory = [System.IO.Path]::GetDirectoryName($fullInputPath)
    $fileName = [System.IO.Path]::GetFileName($fullInputPath)
    if ($fileName.EndsWith(".type-properties-required.openapi.json", [System.StringComparison]::OrdinalIgnoreCase) -or
        $fileName.EndsWith(".type-properties-required.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        return $fullInputPath
    }
    if ($fileName.EndsWith(".openapi.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $stem = $fileName.Substring(0, $fileName.Length - ".openapi.json".Length)
        return Join-Path $directory "$stem.type-properties-required.openapi.json"
    }
    if ($fileName.EndsWith(".json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $stem = $fileName.Substring(0, $fileName.Length - ".json".Length)
        return Join-Path $directory "$stem.type-properties-required.json"
    }
    return Join-Path $directory "$fileName.type-properties-required.json"
}

function Invoke-OpenApiTypePropertyRequirement {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath,

        [Parameter()]
        [string]$OutputPath
    )

    $resolvedInputPath = (Resolve-Path -LiteralPath $InputPath -ErrorAction Stop).ProviderPath
    if (-not [System.IO.File]::Exists($resolvedInputPath)) {
        throw "The OpenAPI input path is not a file: $resolvedInputPath"
    }
    if ([string]::IsNullOrWhiteSpace($OutputPath)) {
        $OutputPath = Get-DefaultRequiredTypePropertiesOpenApiPath -InputPath $resolvedInputPath
    }
    else {
        $OutputPath = [System.IO.Path]::GetFullPath($OutputPath)
    }

    $document = Read-OpenApiDocument -Path $resolvedInputPath
    $result = ConvertTo-OpenApiRequiredTypePropertiesDocument -Document $document
    $writtenPath = Write-OpenApiJsonFile -Document $result.Document -Path $OutputPath

    Write-Host ""
    Write-Host "Input: $resolvedInputPath"
    Write-Host "Output: $writtenPath"
    Write-Host "Object schemas updated: $($result.RequiredTypePropertyCount)"

    return $result
}

if ($MyInvocation.InvocationName -ne ".") {
    if ([string]::IsNullOrWhiteSpace($InputPath)) {
        throw "InputPath is required."
    }
    $null = Invoke-OpenApiTypePropertyRequirement `
        -InputPath $InputPath `
        -OutputPath $OutputPath
}