<#
.SYNOPSIS
    Removes configured properties from an extracted OpenAPI document.

.DESCRIPTION
    Applies the contextual omission policy before references are inlined. Exact
    lowercase metadata names and lowercase x-prefixed extensions are removed,
    while required OpenAPI members and schema-map field names are preserved.
    Surviving values retain encounter order and the input is never modified.

.PARAMETER InputPath
    The extracted OpenAPI JSON document to prune.

.PARAMETER OutputPath
    The destination JSON file. When omitted, a sibling filename is generated by
    inserting '.omitted' before '.openapi.json' or the final '.json' suffix. An
    already-omitted input is atomically rewritten in place.

.EXAMPLE
    ./scripts/specification/pipeline/Remove-OpenApiOmittedProperties.ps1 `
        ./artifacts/openapi-extracts/responses.extracted.openapi.json
    ./scripts/specification/pipeline/Inline-OpenApiReferences.ps1 `
        ./artifacts/openapi-extracts/responses.extracted.omitted.openapi.json
#>

#Requires -Version 7.0

[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string]$InputPath,

    [Parameter()]
    [string]$OutputPath
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$helperPath = Join-Path $PSScriptRoot "_OpenApiDocument.Helpers.ps1"
if (-not (Test-Path -LiteralPath $helperPath -PathType Leaf)) {
    throw "The shared OpenAPI helper script was not found: $helperPath"
}
. $helperPath

$script:OmittedPropertyNames = @(
    "example"
    "examples"
    "title"
    "description"
    "default"
)

function Test-IsOpenApiResponsesObjectBreadcrumb {
    param(
        [Parameter(Mandatory = $true)]
        [string]$Breadcrumb
    )

    $tokens = Get-JsonPointerTokens -Pointer $Breadcrumb
    if ($tokens.Count -eq 2 -and
        [string]::Equals($tokens[0], "components", [System.StringComparison]::Ordinal) -and
        [string]::Equals($tokens[1], "responses", [System.StringComparison]::Ordinal)) {
        return $true
    }

    return $tokens.Count -ge 2 -and
        [string]::Equals($tokens[$tokens.Count - 1], "responses", [System.StringComparison]::Ordinal) -and
        $script:OpenApiHttpMethodNames -ccontains $tokens[$tokens.Count - 2]
}

function Test-IsOpenApiResponseObjectBreadcrumb {
    param(
        [Parameter(Mandatory = $true)]
        [string]$Breadcrumb
    )

    $tokens = Get-JsonPointerTokens -Pointer $Breadcrumb
    if ($tokens.Count -eq 3 -and
        [string]::Equals($tokens[0], "components", [System.StringComparison]::Ordinal) -and
        [string]::Equals($tokens[1], "responses", [System.StringComparison]::Ordinal)) {
        return $true
    }

    return $tokens.Count -ge 3 -and
        [string]::Equals($tokens[$tokens.Count - 2], "responses", [System.StringComparison]::Ordinal) -and
        $script:OpenApiHttpMethodNames -ccontains $tokens[$tokens.Count - 3]
}

function Test-IsOmittedOpenApiProperty {
    param(
        [Parameter(Mandatory = $true)]
        [string]$Name,

        [Parameter()]
        [AllowNull()]
        [object]$ParentObject,

        [Parameter()]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$ParentContext = "OpenApi",

        [Parameter()]
        [string]$ParentBreadcrumb = "#"
    )

    if ($Name.StartsWith("x-", [System.StringComparison]::Ordinal)) {
        return $true
    }
    if ([string]::Equals($ParentContext, "SchemaMap", [System.StringComparison]::Ordinal) -and
        @("title", "description", "default") -ccontains $Name) {
        return $false
    }
    if ([string]::Equals($Name, "title", [System.StringComparison]::Ordinal) -and
        [string]::Equals($ParentBreadcrumb, "#/info", [System.StringComparison]::Ordinal)) {
        return $false
    }
    if ([string]::Equals($Name, "default", [System.StringComparison]::Ordinal) -and
        (Test-IsOpenApiResponsesObjectBreadcrumb -Breadcrumb $ParentBreadcrumb)) {
        return $false
    }
    if ([string]::Equals($Name, "description", [System.StringComparison]::Ordinal) -and
        (Test-IsOpenApiResponseObjectBreadcrumb -Breadcrumb $ParentBreadcrumb) -and
        ($null -eq $ParentObject -or -not (Test-JsonProperty -Object $ParentObject -Name '$ref'))) {
        return $false
    }

    foreach ($omittedPropertyName in $script:OmittedPropertyNames) {
        if ([string]::Equals($Name, $omittedPropertyName, [System.StringComparison]::Ordinal)) {
            return $true
        }
    }
    return $false
}

function ConvertTo-PrunedOpenApiValueInternal {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter()]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context = "OpenApi",

        [Parameter()]
        [string]$Breadcrumb = "#",

        [Parameter(Mandatory = $true)]
        [ref]$RemovedPropertyCount,

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "JSON pruning exceeds the supported depth of $MaximumDepth at '$Breadcrumb'."
    }
    if ($null -eq $Value) {
        return $null
    }
    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        [object[]]$items = [object[]]::new($Value.Count)
        for ($index = 0; $index -lt $Value.Count; $index++) {
            $items[$index] = ConvertTo-PrunedOpenApiValueInternal `
                -Value $Value[$index] `
                -Context $itemContext `
                -Breadcrumb "$Breadcrumb/$index" `
                -RemovedPropertyCount $RemovedPropertyCount `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return ,$items
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return $Value
    }

    $result = [ordered]@{}
    foreach ($property in (Get-JsonProperties -Value $Value)) {
        if (Test-IsOmittedOpenApiProperty `
            -Name $property.Name `
            -ParentObject $Value `
            -ParentContext $Context `
            -ParentBreadcrumb $Breadcrumb) {
            $RemovedPropertyCount.Value++
            continue
        }

        $childBreadcrumb = "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)"
        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        $result[$property.Name] = ConvertTo-PrunedOpenApiValueInternal `
            -Value $property.Value `
            -Context $childContext `
            -Breadcrumb $childBreadcrumb `
            -RemovedPropertyCount $RemovedPropertyCount `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
    return $result
}

function ConvertTo-PrunedOpenApiValue {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter()]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context = "OpenApi",

        [Parameter()]
        [string]$Breadcrumb = "#",

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    $removedPropertyCount = 0
    return ConvertTo-PrunedOpenApiValueInternal `
        -Value $Value `
        -Context $Context `
        -Breadcrumb $Breadcrumb `
        -RemovedPropertyCount ([ref]$removedPropertyCount) `
        -MaximumDepth $MaximumDepth
}

function Assert-NoOmittedOpenApiProperties {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter()]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context = "OpenApi",

        [Parameter()]
        [string]$Breadcrumb = "#",

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "omission postcondition exceeds the supported depth of $MaximumDepth at '$Breadcrumb'."
    }
    if ($null -eq $Value) {
        return
    }
    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        for ($index = 0; $index -lt $Value.Count; $index++) {
            Assert-NoOmittedOpenApiProperties `
                -Value $Value[$index] `
                -Context $itemContext `
                -Breadcrumb "$Breadcrumb/$index" `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return
    }

    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $propertyBreadcrumb = "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)"
        if (Test-IsOmittedOpenApiProperty `
            -Name $property.Name `
            -ParentObject $Value `
            -ParentContext $Context `
            -ParentBreadcrumb $Breadcrumb) {
            throw "Omission output retained '$($property.Name)' at '$propertyBreadcrumb'."
        }
        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        Assert-NoOmittedOpenApiProperties `
            -Value $property.Value `
            -Context $childContext `
            -Breadcrumb $propertyBreadcrumb `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
}

function ConvertTo-OmittedOpenApiPropertiesDocument {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Document
    )

    $removedPropertyCount = 0
    $pruned = ConvertTo-PrunedOpenApiValueInternal `
        -Value $Document `
        -RemovedPropertyCount ([ref]$removedPropertyCount)
    Assert-NoOmittedOpenApiProperties -Value $pruned
    return [PSCustomObject]@{
        Document = $pruned
        RemovedPropertyCount = $removedPropertyCount
    }
}

function Get-DefaultOmittedOpenApiPath {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath
    )

    $fullInputPath = [System.IO.Path]::GetFullPath($InputPath)
    $directory = [System.IO.Path]::GetDirectoryName($fullInputPath)
    $fileName = [System.IO.Path]::GetFileName($fullInputPath)
    if ($fileName.EndsWith(".omitted.openapi.json", [System.StringComparison]::OrdinalIgnoreCase) -or
        $fileName.EndsWith(".omitted.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        return $fullInputPath
    }
    if ($fileName.EndsWith(".openapi.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $baseName = $fileName.Substring(0, $fileName.Length - ".openapi.json".Length)
        return Join-Path $directory "$baseName.omitted.openapi.json"
    }
    if ($fileName.EndsWith(".json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $baseName = $fileName.Substring(0, $fileName.Length - ".json".Length)
        return Join-Path $directory "$baseName.omitted.json"
    }
    return Join-Path $directory "$fileName.omitted.json"
}

function Invoke-OpenApiOmittedPropertyRemoval {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath,

        [Parameter()]
        [string]$OutputPath
    )

    $resolvedInputPath = (Resolve-Path -LiteralPath $InputPath -ErrorAction Stop).ProviderPath
    if (-not [System.IO.File]::Exists($resolvedInputPath)) {
        throw "The OpenAPI input path is not a file: $resolvedInputPath"
    }
    if ([string]::IsNullOrWhiteSpace($OutputPath)) {
        $OutputPath = Get-DefaultOmittedOpenApiPath -InputPath $resolvedInputPath
    }
    else {
        $OutputPath = [System.IO.Path]::GetFullPath($OutputPath)
    }

    $document = Read-OpenApiDocument -Path $resolvedInputPath
    $result = ConvertTo-OmittedOpenApiPropertiesDocument -Document $document
    $writtenPath = Write-OpenApiJsonFile -Document $result.Document -Path $OutputPath

    Write-Host ""
    Write-Host "Input: $resolvedInputPath"
    Write-Host "Output: $writtenPath"
    Write-Host "Properties removed: $($result.RemovedPropertyCount)"

    return $result
}

if ($MyInvocation.InvocationName -ne ".") {
    if ([string]::IsNullOrWhiteSpace($InputPath)) {
        throw "InputPath is required."
    }
    $null = Invoke-OpenApiOmittedPropertyRemoval `
        -InputPath $InputPath `
        -OutputPath $OutputPath
}