<#
.SYNOPSIS
    Reconciles type discriminators on oneOf schema compositions.

.DESCRIPTION
    Adds `discriminator: { propertyName: "type" }` when a nonempty oneOf has
    compatible object branches with disjoint finite discriminator values. Nested
    groups using the same discriminator property contribute their leaves and
    must carry matching structural siblings. A group using a different
    discriminator property remains one branch when every concrete leaf requires
    the same singleton outer discriminator value. That property constraint is
    declared directly on the intermediate base without changing its inner
    discriminator, leaf constraints, or reference locations.

    The discriminator is inserted immediately before oneOf. Existing valid
    discriminators are preserved; existing invalid discriminators are removed
    without changing the oneOf validation. Ambiguous values, near-miss schemas,
    and encounter order outside the metadata change remain unchanged. Run
    Normalize-OpenApiOneOf.ps1, Flatten-OpenApiOneOf.ps1, and
    Wrap-OpenApiSingletonTypeEnums.ps1 before sorting.

    Here invalid means unsupported by the pipeline's conservative analysis, not
    necessarily invalid JSON Schema. This includes malformed discriminator
    metadata/compositions, non-object alternatives, missing or optional
    discriminator properties, non-finite/conflicting const/enum values, and
    overlapping branch values. A NestedDiscriminatorGroup must have a valid
    inner discriminator and one provable common required outer value. A
    FlattenableGroup must meet the same-property structural and scope checks.
    Mappings on retained discriminators are validated during componentization;
    malformed targets or keys then fail rather than being silently discarded. See
    docs/OpenApiPipelineDesign.md for the stage-specific rules and failure behavior.

.PARAMETER InputPath
    The type-enum-split OpenAPI JSON document to update.

.PARAMETER OutputPath
    The destination JSON file. When omitted, a sibling filename is generated by
    inserting '.oneof-discriminated' before '.openapi.json' or the final '.json'
    suffix. Already oneOf-discriminated input is atomically rewritten in place.

.EXAMPLE
    ./scripts/specification/pipeline/Add-OpenApiOneOfDiscriminators.ps1 `
        ./artifacts/custom.type-enum-split.openapi.json `
        -OutputPath ./artifacts/custom.oneof-discriminated.openapi.json
#>

#Requires -Version 7.0

[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string]$InputPath,

    [Parameter()]
    [string]$OutputPath
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$helperPath = Join-Path $PSScriptRoot "_OpenApiDocument.Helpers.ps1"
if (-not (Test-Path -LiteralPath $helperPath -PathType Leaf)) {
    throw "The shared OpenAPI helper script was not found: $helperPath"
}
. $helperPath

function Get-OpenApiOneOfDiscriminatorCandidate {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Schema,

        [Parameter()]
        [switch]$IgnoreExistingDiscriminator
    )

    if ((-not $IgnoreExistingDiscriminator -and
            (Test-JsonProperty -Object $Schema -Name "discriminator")) -or
        -not (Test-JsonProperty -Object $Schema -Name "oneOf")) {
        return $null
    }

    $oneOf = Get-JsonPropertyValue -Object $Schema -Name "oneOf"
    if (-not (Test-JsonArrayValue -Value $oneOf) -or $oneOf.Count -eq 0) {
        return $null
    }

    $plan = Get-OpenApiInlineDiscriminatorUnionPlan `
        -Schema $Schema `
        -PropertyName "type" `
        -Breadcrumb "#" `
        -IgnoreSchemaDiscriminatorMetadata:$IgnoreExistingDiscriminator
    if ($null -eq $plan) {
        return $null
    }

    return [PSCustomObject]@{
        Branches = $oneOf
        EnumValues = [string[]]$plan.Values
        Plan = $plan
    }
}

function Test-IsValidInlineOpenApiOneOfDiscriminator {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Schema
    )

    $discriminator = Get-JsonPropertyValue -Object $Schema -Name "discriminator"
    if (-not (Test-JsonObjectValue -Value $discriminator)) {
        return $false
    }
    $propertyName = Get-JsonPropertyValue -Object $discriminator -Name "propertyName"
    if ($propertyName -isnot [string] -or [string]::IsNullOrWhiteSpace($propertyName)) {
        return $false
    }
    return $null -ne (Get-OpenApiInlineDiscriminatorUnionPlan `
        -Schema $Schema `
        -PropertyName $propertyName `
        -Breadcrumb "#" `
        -RequireDiscriminator)
}

function ConvertTo-OneOfDiscriminatedOpenApiValue {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter(Mandatory = $true)]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context,

        [Parameter(Mandatory = $true)]
        [string]$Breadcrumb,

        [Parameter(Mandatory = $true)]
        [ref]$AddedDiscriminatorCount,

        [Parameter(Mandatory = $true)]
        [ref]$RemovedInvalidDiscriminatorCount,

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "oneOf discriminator inference exceeds the supported depth of $MaximumDepth at '$Breadcrumb'."
    }
    if ($null -eq $Value) {
        return $null
    }
    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        [object[]]$items = [object[]]::new($Value.Count)
        for ($index = 0; $index -lt $Value.Count; $index++) {
            $items[$index] = ConvertTo-OneOfDiscriminatedOpenApiValue `
                -Value $Value[$index] `
                -Context $itemContext `
                -Breadcrumb "$Breadcrumb/$index" `
                -AddedDiscriminatorCount $AddedDiscriminatorCount `
                -RemovedInvalidDiscriminatorCount $RemovedInvalidDiscriminatorCount `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return ,$items
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return $Value
    }

    $removeInvalidDiscriminator = [string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal) -and
        (Test-JsonProperty -Object $Value -Name "oneOf") -and
        (Test-JsonProperty -Object $Value -Name "discriminator") -and
        -not (Test-IsValidInlineOpenApiOneOfDiscriminator -Schema $Value)
    $candidate = if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal)) {
        Get-OpenApiOneOfDiscriminatorCandidate `
            -Schema $Value `
            -IgnoreExistingDiscriminator:$removeInvalidDiscriminator
    }
    else {
        $null
    }

    $normalizationPlan = if ($null -ne $candidate) {
        $candidate.Plan
    }
    elseif ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal) -and
        (Test-JsonProperty -Object $Value -Name "oneOf") -and
        (Test-IsValidInlineOpenApiOneOfDiscriminator -Schema $Value)) {
        $discriminator = Get-JsonPropertyValue -Object $Value -Name "discriminator"
        Get-OpenApiInlineDiscriminatorUnionPlan `
            -Schema $Value `
            -PropertyName (Get-JsonPropertyValue -Object $discriminator -Name "propertyName") `
            -Breadcrumb $Breadcrumb `
            -RequireDiscriminator
    }
    else {
        $null
    }
    if ($null -ne $normalizationPlan) {
        $Value = ConvertTo-NormalizedOpenApiDiscriminatorUnionSchema `
            -Plan $normalizationPlan `
            -MaximumDepth ($MaximumDepth - $Depth)
    }

    $result = [ordered]@{}
    foreach ($property in (Get-JsonProperties -Value $Value)) {
        if ($removeInvalidDiscriminator -and
            [string]::Equals($property.Name, "discriminator", [System.StringComparison]::Ordinal)) {
            $RemovedInvalidDiscriminatorCount.Value++
            continue
        }
        if ($null -ne $candidate -and
            [string]::Equals($property.Name, "oneOf", [System.StringComparison]::Ordinal)) {
            $result["discriminator"] = [ordered]@{
                propertyName = "type"
            }
            $AddedDiscriminatorCount.Value++
        }

        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        $result[$property.Name] = ConvertTo-OneOfDiscriminatedOpenApiValue `
            -Value $property.Value `
            -Context $childContext `
            -Breadcrumb "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)" `
            -AddedDiscriminatorCount $AddedDiscriminatorCount `
            -RemovedInvalidDiscriminatorCount $RemovedInvalidDiscriminatorCount `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
    return $result
}

function Assert-NoUndiscriminatedOpenApiOneOfCandidates {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter()]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context = "OpenApi",

        [Parameter()]
        [string]$Breadcrumb = "#",

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "oneOf discriminator postcondition exceeds the supported depth of $MaximumDepth at '$Breadcrumb'."
    }
    if ($null -eq $Value) {
        return
    }
    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        for ($index = 0; $index -lt $Value.Count; $index++) {
            Assert-NoUndiscriminatedOpenApiOneOfCandidates `
                -Value $Value[$index] `
                -Context $itemContext `
                -Breadcrumb "$Breadcrumb/$index" `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return
    }

    if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal) -and
        $null -ne (Get-OpenApiOneOfDiscriminatorCandidate -Schema $Value)) {
        throw "Output retained an eligible undiscriminated oneOf at '$Breadcrumb/oneOf'."
    }

    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        Assert-NoUndiscriminatedOpenApiOneOfCandidates `
            -Value $property.Value `
            -Context $childContext `
            -Breadcrumb "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)" `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
}

function ConvertTo-OneOfDiscriminatedOpenApiDocument {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Document
    )

    $addedDiscriminatorCount = 0
    $removedInvalidDiscriminatorCount = 0
    $converted = ConvertTo-OneOfDiscriminatedOpenApiValue `
        -Value $Document `
        -Context OpenApi `
        -Breadcrumb "#" `
        -AddedDiscriminatorCount ([ref]$addedDiscriminatorCount) `
        -RemovedInvalidDiscriminatorCount ([ref]$removedInvalidDiscriminatorCount)

    Assert-OpenApiReferencesResolve -Document $converted
    Assert-AdditionalOpenApiReferencesResolve -Document $converted
    Assert-NoUndiscriminatedOpenApiOneOfCandidates -Value $converted

    return [PSCustomObject]@{
        Document = $converted
        AddedDiscriminatorCount = $addedDiscriminatorCount
        RemovedInvalidDiscriminatorCount = $removedInvalidDiscriminatorCount
    }
}

function Get-DefaultOneOfDiscriminatedOpenApiPath {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath
    )

    $fullInputPath = [System.IO.Path]::GetFullPath($InputPath)
    $directory = [System.IO.Path]::GetDirectoryName($fullInputPath)
    $fileName = [System.IO.Path]::GetFileName($fullInputPath)
    if ($fileName.EndsWith(".oneof-discriminated.openapi.json", [System.StringComparison]::OrdinalIgnoreCase) -or
        $fileName.EndsWith(".oneof-discriminated.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        return $fullInputPath
    }
    if ($fileName.EndsWith(".openapi.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $baseName = $fileName.Substring(0, $fileName.Length - ".openapi.json".Length)
        return Join-Path $directory "$baseName.oneof-discriminated.openapi.json"
    }
    if ($fileName.EndsWith(".json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $baseName = $fileName.Substring(0, $fileName.Length - ".json".Length)
        return Join-Path $directory "$baseName.oneof-discriminated.json"
    }
    return Join-Path $directory "$fileName.oneof-discriminated.json"
}

function Invoke-OpenApiOneOfDiscriminatorAdder {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath,

        [Parameter()]
        [string]$OutputPath
    )

    $resolvedInputPath = (Resolve-Path -LiteralPath $InputPath -ErrorAction Stop).ProviderPath
    if (-not [System.IO.File]::Exists($resolvedInputPath)) {
        throw "The OpenAPI input path is not a file: $resolvedInputPath"
    }
    if ([string]::IsNullOrWhiteSpace($OutputPath)) {
        $OutputPath = Get-DefaultOneOfDiscriminatedOpenApiPath -InputPath $resolvedInputPath
    }
    else {
        $OutputPath = [System.IO.Path]::GetFullPath($OutputPath)
    }

    $document = Read-OpenApiDocument -Path $resolvedInputPath
    $result = ConvertTo-OneOfDiscriminatedOpenApiDocument -Document $document
    $writtenPath = Write-OpenApiJsonFile -Document $result.Document -Path $OutputPath

    Write-Host ""
    Write-Host "Input: $resolvedInputPath"
    Write-Host "Output: $writtenPath"
    Write-Host "oneOf discriminators added: $($result.AddedDiscriminatorCount)"
    Write-Host "Invalid oneOf discriminators removed: $($result.RemovedInvalidDiscriminatorCount)"

    return $result
}

# Dot-sourcing exposes conversion functions to tests without running the CLI.
if ($MyInvocation.InvocationName -ne ".") {
    if ([string]::IsNullOrWhiteSpace($InputPath)) {
        throw "InputPath is required."
    }
    $null = Invoke-OpenApiOneOfDiscriminatorAdder `
        -InputPath $InputPath `
        -OutputPath $OutputPath
}
