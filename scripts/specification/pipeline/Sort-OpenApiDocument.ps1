<#
.SYNOPSIS
    Canonically sorts an extracted OpenAPI JSON document.

.DESCRIPTION
    Applies deterministic ordering to schema definitions without changing their
    semantics. The sorter supports Inlined, allOf-flattened,
    string-variant-simplified, recursive-schema-simplified, oneOf-normalized,
    oneOf-flattened, and singleton-type-wrapped output from the OpenAPI scripts,
    including inferred oneOf discriminators. It orders schema keys, property
    maps, required arrays, enum arrays, and oneOf branches. Ordinary oneOf
    branches with a direct scalar type sort by that type before an encounter-
    ordered unclassifiable tail. Discriminated oneOf branches sort by their
    ordinal-smallest accepted discriminator value. Other non-enum arrays retain
    encounter order. Local JSON Pointers are relocated when branch indexes move.

.PARAMETER InputPath
    The extracted OpenAPI JSON document to sort.

.PARAMETER OutputPath
    The destination JSON file. When omitted, a sibling filename is generated by
    inserting '.sorted' before '.openapi.json' or the final '.json' suffix. An
    already-sorted input is atomically rewritten in place.

.EXAMPLE
    ./scripts/specification/pipeline/Sort-OpenApiDocument.ps1 `
        ./artifacts/openapi-extracts/responses.inlined.flattened.simplified.recursive-simplified.type-enum-split.oneof-discriminated.oneof-normalized.oneof-flattened.singleton-type-wrapped.openapi.json

#>

#Requires -Version 7.0

[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string]$InputPath,

    [Parameter()]
    [string]$OutputPath
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$helperPath = Join-Path $PSScriptRoot "_OpenApiDocument.Helpers.ps1"
if (-not (Test-Path -LiteralPath $helperPath -PathType Leaf)) {
    throw "The shared OpenAPI helper script was not found: $helperPath"
}
. $helperPath

# Schema keys listed here are emitted first and in this exact order. Remaining
# schema keys follow alphabetically.
$script:PrioritizedSchemaPropertyNames = @(
    "type"
    "description"
    "required"
    "properties"
)

# Required names listed here lead both schema required arrays and required names
# inside properties maps. Optional properties are never promoted.
$script:PrioritizedRequiredPropertyNames = @(
    "type"
)

function Sort-OrdinalStrings {
    param(
        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [string[]]$Values
    )

    [string[]]$sortedValues = @($Values)
    [System.Array]::Sort($sortedValues, [System.StringComparer]::Ordinal)
    return ,$sortedValues
}

# Sorts enum values by compact JSON text while preserving each value's JSON type
# and the relative order of structurally equal values.
function Sort-JsonEnumValues {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [AllowEmptyCollection()]
        [object[]]$Values
    )

    if ($null -eq $Values) {
        return ,([object[]]@($null))
    }

    $sortedEntries = [System.Collections.Generic.List[object]]::new()
    foreach ($value in $Values) {
        $entry = [PSCustomObject]@{
            Key = ConvertTo-Json -InputObject $value -Compress -Depth 100
            Value = $value
        }
        $insertionIndex = $sortedEntries.Count
        for ($index = 0; $index -lt $sortedEntries.Count; $index++) {
            if ([System.StringComparer]::Ordinal.Compare($entry.Key, $sortedEntries[$index].Key) -lt 0) {
                $insertionIndex = $index
                break
            }
        }
        $sortedEntries.Insert($insertionIndex, $entry)
    }

    [object[]]$sortedValues = [object[]]::new($sortedEntries.Count)
    for ($index = 0; $index -lt $sortedEntries.Count; $index++) {
        $sortedValues[$index] = $sortedEntries[$index].Value
    }
    return ,$sortedValues
}

function Get-OpenApiSortedDiscriminatorBranchValues {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Document,

        [Parameter(Mandatory = $true)]
        [object]$Branch,

        [Parameter(Mandatory = $true)]
        [string]$PropertyName,

        [Parameter(Mandatory = $true)]
        [string]$Breadcrumb
    )

    if (-not (Test-JsonObjectValue -Value $Branch)) {
        throw "Cannot sort discriminated oneOf branch at '$Breadcrumb' by property '$PropertyName' because the branch is not a Schema Object."
    }

    $targetSchema = $Branch
    $branchProperties = @(Get-JsonProperties -Value $Branch)
    if ($branchProperties.Count -eq 1 -and
        [string]::Equals($branchProperties[0].Name, '$ref', [System.StringComparison]::Ordinal)) {
        $reference = $branchProperties[0].Value
        if ($reference -isnot [string] -or
            -not $reference.StartsWith("#/", [System.StringComparison]::Ordinal)) {
            throw "Cannot sort discriminated oneOf branch at '$Breadcrumb' by property '$PropertyName' because its `$ref is not a local JSON Pointer."
        }
        try {
            $targetSchema = Resolve-LocalJsonPointer `
                -Document $Document `
                -Pointer $reference `
                -Context "discriminated oneOf branch at $Breadcrumb"
        }
        catch {
            throw "Cannot sort discriminated oneOf branch at '$Breadcrumb' by property '$PropertyName': $($_.Exception.Message)"
        }
    }
    elseif (Test-JsonProperty -Object $Branch -Name "oneOf") {
        $nestedPlan = Get-OpenApiInlineDiscriminatorUnionPlan `
            -Schema $Branch `
            -PropertyName $PropertyName `
            -Breadcrumb $Breadcrumb `
            -RequireDiscriminator
        if ($null -eq $nestedPlan -or $nestedPlan.Values.Count -eq 0) {
            throw "Cannot sort discriminated oneOf branch at '$Breadcrumb' by property '$PropertyName' because it does not expose finite discriminator values."
        }
        return ,(Sort-OrdinalStrings -Values ([string[]]$nestedPlan.Values))
    }

    try {
        [string[]]$values = @(Get-OpenApiDiscriminatorPropertyValues `
            -Schema $targetSchema `
            -PropertyName $PropertyName `
            -Breadcrumb $Breadcrumb)
    }
    catch {
        throw "Cannot sort discriminated oneOf branch at '$Breadcrumb' by property '$PropertyName': $($_.Exception.Message)"
    }
    if ($values.Count -eq 0) {
        throw "Cannot sort discriminated oneOf branch at '$Breadcrumb' by property '$PropertyName' because it does not accept a finite string value."
    }
    return ,(Sort-OrdinalStrings -Values $values)
}

function Compare-OpenApiOneOfSortEntries {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Left,

        [Parameter(Mandatory = $true)]
        [object]$Right,

        [Parameter()]
        [switch]$Discriminated
    )

    if (-not $Discriminated -and $Left.IsClassifiable -ne $Right.IsClassifiable) {
        if ($Left.IsClassifiable) {
            return -1
        }
        return 1
    }
    if ($Left.IsClassifiable -and $Right.IsClassifiable) {
        $keyComparison = [System.StringComparer]::Ordinal.Compare($Left.SortKey, $Right.SortKey)
        if ($keyComparison -ne 0) {
            return $keyComparison
        }
    }
    return $Left.OriginalIndex.CompareTo($Right.OriginalIndex)
}

function ConvertTo-SortedOpenApiOneOfBranches {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Document,

        [Parameter(Mandatory = $true)]
        [object]$OwnerSchema,

        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [object[]]$Branches,

        [Parameter(Mandatory = $true)]
        [string]$Breadcrumb,

        [Parameter(Mandatory = $true)]
        [System.Collections.Generic.Dictionary[string, object]]$OneOfPermutations,

        [Parameter(Mandatory = $true)]
        [int]$Depth,

        [Parameter(Mandatory = $true)]
        [int]$MaximumDepth
    )

    $isDiscriminated = Test-JsonProperty -Object $OwnerSchema -Name "discriminator"
    $discriminator = if ($isDiscriminated) {
        Get-JsonPropertyValue -Object $OwnerSchema -Name "discriminator"
    }
    else {
        $null
    }
    $propertyName = $null
    if ($isDiscriminated) {
        $ownerBreadcrumb = $Breadcrumb.Substring(0, $Breadcrumb.Length - "/oneOf".Length)
        if (-not (Test-JsonObjectValue -Value $discriminator)) {
            throw "Discriminator at '$ownerBreadcrumb/discriminator' must be an object before its oneOf can be sorted."
        }
        $propertyName = Get-JsonPropertyValue -Object $discriminator -Name "propertyName"
        if ($propertyName -isnot [string] -or [string]::IsNullOrWhiteSpace($propertyName)) {
            throw "Discriminator propertyName at '$ownerBreadcrumb/discriminator/propertyName' must be a nonempty string before its oneOf can be sorted."
        }
    }

    $sortedEntries = [System.Collections.Generic.List[object]]::new()
    for ($index = 0; $index -lt $Branches.Count; $index++) {
        $branchBreadcrumb = "$Breadcrumb/$index"
        $sortedBranch = ConvertTo-SortedOpenApiValue `
            -Value $Branches[$index] `
            -Context Schema `
            -Document $Document `
            -Breadcrumb $branchBreadcrumb `
            -OneOfPermutations $OneOfPermutations `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth

        $isClassifiable = $false
        $sortKey = $null
        if ($isDiscriminated) {
            [string[]]$acceptedValues = @(Get-OpenApiSortedDiscriminatorBranchValues `
                -Document $Document `
                -Branch $Branches[$index] `
                -PropertyName $propertyName `
                -Breadcrumb $branchBreadcrumb)
            $isClassifiable = $true
            $sortKey = $acceptedValues[0]
        }
        elseif (Test-JsonObjectValue -Value $Branches[$index]) {
            $branchType = Get-JsonPropertyValue -Object $Branches[$index] -Name "type"
            if ($branchType -is [string]) {
                $isClassifiable = $true
                $sortKey = $branchType
            }
        }

        $entry = [PSCustomObject]@{
            OriginalIndex = $index
            IsClassifiable = $isClassifiable
            SortKey = $sortKey
            Value = $sortedBranch
        }
        $insertionIndex = $sortedEntries.Count
        for ($sortedIndex = 0; $sortedIndex -lt $sortedEntries.Count; $sortedIndex++) {
            if ((Compare-OpenApiOneOfSortEntries `
                    -Left $entry `
                    -Right $sortedEntries[$sortedIndex] `
                    -Discriminated:$isDiscriminated) -lt 0) {
                $insertionIndex = $sortedIndex
                break
            }
        }
        $sortedEntries.Insert($insertionIndex, $entry)
    }

    [object[]]$sortedBranches = [object[]]::new($sortedEntries.Count)
    [int[]]$oldToNew = [int[]]::new($sortedEntries.Count)
    $changed = $false
    for ($newIndex = 0; $newIndex -lt $sortedEntries.Count; $newIndex++) {
        $entry = $sortedEntries[$newIndex]
        $sortedBranches[$newIndex] = $entry.Value
        $oldToNew[$entry.OriginalIndex] = $newIndex
        if ($entry.OriginalIndex -ne $newIndex) {
            $changed = $true
        }
    }
    if ($changed) {
        if ($OneOfPermutations.ContainsKey($Breadcrumb)) {
            throw "oneOf sorting registered duplicate permutations for '$Breadcrumb'."
        }
        $OneOfPermutations[$Breadcrumb] = $oldToNew
    }
    return ,$sortedBranches
}

function Get-SortedOpenApiOneOfPointer {
    param(
        [Parameter(Mandatory = $true)]
        [string]$Pointer,

        [Parameter(Mandatory = $true)]
        [System.Collections.Generic.Dictionary[string, object]]$OneOfPermutations
    )

    if ([string]::Equals($Pointer, "#", [System.StringComparison]::Ordinal) -or
        -not $Pointer.StartsWith("#/", [System.StringComparison]::Ordinal) -or
        $OneOfPermutations.Count -eq 0) {
        return $Pointer
    }

    [string[]]$tokens = Get-JsonPointerTokens -Pointer $Pointer
    $originalPrefix = "#"
    $sortedPrefix = "#"
    foreach ($token in $tokens) {
        $sortedToken = $token
        if ($OneOfPermutations.ContainsKey($originalPrefix)) {
            $oldIndex = 0
            if (-not [int]::TryParse(
                    $token,
                    [System.Globalization.NumberStyles]::None,
                    [System.Globalization.CultureInfo]::InvariantCulture,
                    [ref]$oldIndex)) {
                throw "JSON Pointer '$Pointer' has nonnumeric branch token '$token' below reordered oneOf '$originalPrefix'."
            }
            [int[]]$permutation = [int[]]$OneOfPermutations[$originalPrefix]
            if ($oldIndex -lt 0 -or $oldIndex -ge $permutation.Count) {
                throw "JSON Pointer '$Pointer' has out-of-range branch index '$oldIndex' below reordered oneOf '$originalPrefix'."
            }
            $sortedToken = $permutation[$oldIndex].ToString([System.Globalization.CultureInfo]::InvariantCulture)
        }
        $originalPrefix = "$originalPrefix/$(ConvertTo-JsonPointerToken -Token $token)"
        $sortedPrefix = "$sortedPrefix/$(ConvertTo-JsonPointerToken -Token $sortedToken)"
    }
    return $sortedPrefix
}

function ConvertTo-SortedOpenApiPointers {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter(Mandatory = $true)]
        [System.Collections.Generic.Dictionary[string, object]]$OneOfPermutations,

        [Parameter()]
        [ValidateSet("Default", "Discriminator", "Mapping")]
        [string]$Context = "Default",

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "oneOf pointer relocation exceeds the supported depth of $MaximumDepth."
    }
    if ($null -eq $Value) {
        return $null
    }
    if (Test-JsonArrayValue -Value $Value) {
        [object[]]$items = [object[]]::new($Value.Count)
        for ($index = 0; $index -lt $Value.Count; $index++) {
            $items[$index] = ConvertTo-SortedOpenApiPointers `
                -Value $Value[$index] `
                -OneOfPermutations $OneOfPermutations `
                -Context Default `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return ,$items
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return $Value
    }

    $result = [ordered]@{}
    foreach ($property in (Get-JsonProperties -Value $Value)) {
        if ([string]::Equals($Context, "Mapping", [System.StringComparison]::Ordinal) -and
            $property.Value -is [string]) {
            $result[$property.Name] = Get-SortedOpenApiOneOfPointer `
                -Pointer $property.Value `
                -OneOfPermutations $OneOfPermutations
            continue
        }
        if (@('$ref', '$dynamicRef', '$recursiveRef') -ccontains $property.Name -and
            $property.Value -is [string]) {
            $result[$property.Name] = Get-SortedOpenApiOneOfPointer `
                -Pointer $property.Value `
                -OneOfPermutations $OneOfPermutations
            continue
        }

        $childContext = "Default"
        if ([string]::Equals($Context, "Default", [System.StringComparison]::Ordinal) -and
            [string]::Equals($property.Name, "discriminator", [System.StringComparison]::Ordinal)) {
            $childContext = "Discriminator"
        }
        elseif ([string]::Equals($Context, "Discriminator", [System.StringComparison]::Ordinal) -and
            [string]::Equals($property.Name, "mapping", [System.StringComparison]::Ordinal)) {
            $childContext = "Mapping"
        }
        $result[$property.Name] = ConvertTo-SortedOpenApiPointers `
            -Value $property.Value `
            -OneOfPermutations $OneOfPermutations `
            -Context $childContext `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
    return $result
}

function Get-OrderedRequiredPropertyNames {
    param(
        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [string[]]$RequiredNames
    )

    $availableNames = [System.Collections.Generic.HashSet[string]]::new(
        [System.StringComparer]::Ordinal
    )
    foreach ($requiredName in $RequiredNames) {
        $null = $availableNames.Add($requiredName)
    }

    $emittedNames = [System.Collections.Generic.HashSet[string]]::new(
        [System.StringComparer]::Ordinal
    )
    $orderedNames = [System.Collections.Generic.List[string]]::new()
    foreach ($requiredName in $script:PrioritizedRequiredPropertyNames) {
        if ($availableNames.Contains($requiredName) -and $emittedNames.Add($requiredName)) {
            $orderedNames.Add($requiredName)
        }
    }

    [string[]]$remainingNames = @($availableNames | Where-Object {
        -not $emittedNames.Contains($_)
    })
    foreach ($requiredName in (Sort-OrdinalStrings -Values $remainingNames)) {
        if ($emittedNames.Add($requiredName)) {
            $orderedNames.Add($requiredName)
        }
    }
    return [string[]]$orderedNames
}

function Get-OrderedSchemaPropertyNames {
    param(
        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [string[]]$PropertyNames,

        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [System.Collections.Generic.HashSet[string]]$RequiredNames
    )

    $availableNames = [System.Collections.Generic.HashSet[string]]::new(
        [System.StringComparer]::Ordinal
    )
    foreach ($propertyName in $PropertyNames) {
        $null = $availableNames.Add($propertyName)
    }

    $emittedNames = [System.Collections.Generic.HashSet[string]]::new(
        [System.StringComparer]::Ordinal
    )
    $orderedNames = [System.Collections.Generic.List[string]]::new()
    [string[]]$requiredNameValues = @($RequiredNames | ForEach-Object { $_ })
    foreach ($propertyName in (Get-OrderedRequiredPropertyNames -RequiredNames $requiredNameValues)) {
        if ($availableNames.Contains($propertyName) -and $emittedNames.Add($propertyName)) {
            $orderedNames.Add($propertyName)
        }
    }

    [string[]]$optionalNames = @($PropertyNames | Where-Object {
        -not $RequiredNames.Contains($_)
    })
    foreach ($propertyName in (Sort-OrdinalStrings -Values $optionalNames)) {
        if ($emittedNames.Add($propertyName)) {
            $orderedNames.Add($propertyName)
        }
    }
    return ,([string[]]$orderedNames)
}

function ConvertTo-OrderedSchemaDefinition {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Schema
    )

    $orderedSchema = [ordered]@{}
    $emittedNames = [System.Collections.Generic.HashSet[string]]::new(
        [System.StringComparer]::Ordinal
    )
    foreach ($propertyName in $script:PrioritizedSchemaPropertyNames) {
        if ($emittedNames.Add($propertyName) -and
            (Test-JsonProperty -Object $Schema -Name $propertyName)) {
            $orderedSchema[$propertyName] = Get-JsonPropertyValue -Object $Schema -Name $propertyName
        }
    }

    [string[]]$remainingNames = @(Get-JsonProperties -Value $Schema | Where-Object {
        -not $emittedNames.Contains($_.Name)
    } | ForEach-Object Name)
    foreach ($propertyName in (Sort-OrdinalStrings -Values $remainingNames)) {
        $orderedSchema[$propertyName] = Get-JsonPropertyValue -Object $Schema -Name $propertyName
    }
    return $orderedSchema
}

# Recursively applies canonical ordering only to schema definitions. It does not
# omit fields or alter non-schema object and non-enum array order.
function ConvertTo-SortedOpenApiValue {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter()]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context = "OpenApi",

        [Parameter()]
        [AllowNull()]
        [object]$Document,

        [Parameter()]
        [string]$Breadcrumb = "#",

        [Parameter()]
        [AllowNull()]
        [System.Collections.Generic.Dictionary[string, object]]$OneOfPermutations,

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "JSON sorting exceeds the supported depth of $MaximumDepth at '$Breadcrumb'."
    }
    if ($null -eq $Document) {
        $Document = $Value
    }
    if ($null -eq $OneOfPermutations) {
        $OneOfPermutations = [System.Collections.Generic.Dictionary[string, object]]::new(
            [System.StringComparer]::Ordinal
        )
    }
    if ($null -eq $Value) {
        return $null
    }
    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        [object[]]$items = [object[]]::new($Value.Count)
        for ($index = 0; $index -lt $Value.Count; $index++) {
            $items[$index] = ConvertTo-SortedOpenApiValue `
                -Value $Value[$index] `
                -Context $itemContext `
                -Document $Document `
                -Breadcrumb "$Breadcrumb/$index" `
                -OneOfPermutations $OneOfPermutations `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return ,$items
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return $Value
    }
    if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
        $Context = "Schema"
    }

    $requiredNames = [System.Collections.Generic.HashSet[string]]::new(
        [System.StringComparer]::Ordinal
    )
    if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal)) {
        $required = Get-JsonPropertyValue -Object $Value -Name "required"
        if (Test-JsonArrayValue -Value $required) {
            foreach ($requiredName in $required) {
                if ($requiredName -isnot [string]) {
                    throw "Every required name must be a string."
                }
                $null = $requiredNames.Add($requiredName)
            }
        }
    }

    $result = [ordered]@{}
    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $propertyBreadcrumb = "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)"
        if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal) -and
            [string]::Equals($property.Name, "enum", [System.StringComparison]::Ordinal) -and
            (Test-JsonArrayValue -Value $property.Value)) {
            [object[]]$enumValues = [object[]]::new($property.Value.Count)
            for ($index = 0; $index -lt $property.Value.Count; $index++) {
                $enumValues[$index] = ConvertTo-SortedOpenApiValue `
                    -Value $property.Value[$index] `
                    -Context Literal `
                    -Document $Document `
                    -Breadcrumb "$propertyBreadcrumb/$index" `
                    -OneOfPermutations $OneOfPermutations `
                    -Depth ($Depth + 1) `
                    -MaximumDepth $MaximumDepth
            }
            $result[$property.Name] = Sort-JsonEnumValues -Values $enumValues
            continue
        }

        if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal) -and
            [string]::Equals($property.Name, "oneOf", [System.StringComparison]::Ordinal) -and
            (Test-JsonArrayValue -Value $property.Value)) {
            $result[$property.Name] = ConvertTo-SortedOpenApiOneOfBranches `
                -Document $Document `
                -OwnerSchema $Value `
                -Branches ([object[]]$property.Value) `
                -Breadcrumb $propertyBreadcrumb `
                -OneOfPermutations $OneOfPermutations `
                -Depth $Depth `
                -MaximumDepth $MaximumDepth
            continue
        }

        if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal) -and
            [string]::Equals($property.Name, "required", [System.StringComparison]::Ordinal) -and
            (Test-JsonArrayValue -Value $property.Value)) {
            [string[]]$requiredNameValues = @(
                foreach ($requiredName in $property.Value) {
                    if ($requiredName -isnot [string]) {
                        throw "Every required name must be a string."
                    }
                    $requiredName
                }
            )
            $result[$property.Name] = @(
                Get-OrderedRequiredPropertyNames -RequiredNames $requiredNameValues
            )
            continue
        }

        if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal) -and
            [string]::Equals($property.Name, "properties", [System.StringComparison]::Ordinal) -and
            (Test-JsonObjectValue -Value $property.Value)) {
            [string[]]$propertyNames = @(
                Get-JsonProperties -Value $property.Value | ForEach-Object Name
            )
            $orderedProperties = [ordered]@{}
            foreach ($propertyName in (Get-OrderedSchemaPropertyNames `
                -PropertyNames $propertyNames `
                -RequiredNames $requiredNames)) {
                $orderedProperties[$propertyName] = ConvertTo-SortedOpenApiValue `
                    -Value (Get-JsonPropertyValue -Object $property.Value -Name $propertyName) `
                    -Context Schema `
                    -Document $Document `
                    -Breadcrumb "$propertyBreadcrumb/$(ConvertTo-JsonPointerToken -Token $propertyName)" `
                    -OneOfPermutations $OneOfPermutations `
                    -Depth ($Depth + 1) `
                    -MaximumDepth $MaximumDepth
            }
            $result[$property.Name] = $orderedProperties
            continue
        }

        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        $result[$property.Name] = ConvertTo-SortedOpenApiValue `
            -Value $property.Value `
            -Context $childContext `
            -Document $Document `
            -Breadcrumb $propertyBreadcrumb `
            -OneOfPermutations $OneOfPermutations `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }

    if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal)) {
        return ConvertTo-OrderedSchemaDefinition -Schema $result
    }
    return $result
}

function ConvertTo-SortedOpenApiDocument {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Document
    )

    $oneOfPermutations = [System.Collections.Generic.Dictionary[string, object]]::new(
        [System.StringComparer]::Ordinal
    )
    $sorted = ConvertTo-SortedOpenApiValue `
        -Value $Document `
        -Document $Document `
        -OneOfPermutations $oneOfPermutations
    if ($oneOfPermutations.Count -gt 0) {
        $sorted = ConvertTo-SortedOpenApiPointers `
            -Value $sorted `
            -OneOfPermutations $oneOfPermutations
    }
    Assert-OpenApiReferencesResolve -Document $sorted
    Assert-AdditionalOpenApiReferencesResolve -Document $sorted
    return $sorted
}

function Get-DefaultSortedOpenApiPath {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath
    )

    $fullInputPath = [System.IO.Path]::GetFullPath($InputPath)
    $directory = [System.IO.Path]::GetDirectoryName($fullInputPath)
    $fileName = [System.IO.Path]::GetFileName($fullInputPath)
    if ($fileName.EndsWith(".sorted.openapi.json", [System.StringComparison]::OrdinalIgnoreCase) -or
        $fileName.EndsWith(".sorted.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        return $fullInputPath
    }
    if ($fileName.EndsWith(".openapi.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $baseName = $fileName.Substring(0, $fileName.Length - ".openapi.json".Length)
        return Join-Path $directory "$baseName.sorted.openapi.json"
    }
    if ($fileName.EndsWith(".json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $baseName = $fileName.Substring(0, $fileName.Length - ".json".Length)
        return Join-Path $directory "$baseName.sorted.json"
    }
    return Join-Path $directory "$fileName.sorted.json"
}

function Invoke-OpenApiDocumentSorter {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath,

        [Parameter()]
        [string]$OutputPath
    )

    $resolvedInputPath = (Resolve-Path -LiteralPath $InputPath -ErrorAction Stop).ProviderPath
    if (-not [System.IO.File]::Exists($resolvedInputPath)) {
        throw "The OpenAPI input path is not a file: $resolvedInputPath"
    }
    if ([string]::IsNullOrWhiteSpace($OutputPath)) {
        $OutputPath = Get-DefaultSortedOpenApiPath -InputPath $resolvedInputPath
    }
    else {
        $OutputPath = [System.IO.Path]::GetFullPath($OutputPath)
    }

    $document = Read-OpenApiDocument -Path $resolvedInputPath
    $sorted = ConvertTo-SortedOpenApiDocument -Document $document
    $writtenPath = Write-OpenApiJsonFile -Document $sorted -Path $OutputPath

    Write-Host ""
    Write-Host "Input: $resolvedInputPath"
    Write-Host "Output: $writtenPath"

    return $sorted
}

if ($MyInvocation.InvocationName -ne ".") {
    if ([string]::IsNullOrWhiteSpace($InputPath)) {
        throw "InputPath is required."
    }
    $null = Invoke-OpenApiDocumentSorter -InputPath $InputPath -OutputPath $OutputPath
}
