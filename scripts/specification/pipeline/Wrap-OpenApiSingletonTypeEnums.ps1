<#
.SYNOPSIS
    Wraps required singleton object type enums in discriminated oneOf schemas.

.DESCRIPTION
    Ensures every Schema Object with a required string property named `type`
    constrained by exactly one enum value is a direct branch of a oneOf whose
    discriminator propertyName is `type`.

    In an undiscriminated mixed oneOf, all qualifying direct object branches are
    moved into one shared nested discriminated oneOf at the position of the first
    qualifying branch. Qualifying schemas in every other position receive a
    singleton discriminated oneOf wrapper. Existing valid type-discriminated
    oneOf schemas remain unchanged.

    Run this stage after Flatten-OpenApiOneOf.ps1 and before sorting.

.PARAMETER InputPath
    The oneOf-flattened OpenAPI JSON document to wrap.

.PARAMETER OutputPath
    The destination JSON file. When omitted, a sibling filename is generated by
    inserting '.singleton-type-wrapped' before '.openapi.json' or the final
    '.json' suffix. Already wrapped input is atomically rewritten in place.

.EXAMPLE
    ./scripts/specification/pipeline/Wrap-OpenApiSingletonTypeEnums.ps1 `
        ./artifacts/custom.oneof-flattened.openapi.json `
        -OutputPath ./artifacts/custom.singleton-type-wrapped.openapi.json
#>

#Requires -Version 7.0

[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string]$InputPath,

    [Parameter()]
    [string]$OutputPath
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$helperPath = Join-Path $PSScriptRoot "_OpenApiDocument.Helpers.ps1"
if (-not (Test-Path -LiteralPath $helperPath -PathType Leaf)) {
    throw "The shared OpenAPI helper script was not found: $helperPath"
}
. $helperPath

function Get-WrappableOpenApiSingletonTypeEnumPlan {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Schema,

        [Parameter(Mandatory = $true)]
        [string]$Breadcrumb
    )

    if (-not (Test-JsonObjectValue -Value $Schema)) {
        return $null
    }
    $schemaType = Get-JsonPropertyValue -Object $Schema -Name "type"
    if ($schemaType -isnot [string] -or
        -not [string]::Equals($schemaType, "object", [System.StringComparison]::Ordinal)) {
        return $null
    }

    $required = Get-JsonPropertyValue -Object $Schema -Name "required"
    if (-not (Test-JsonArrayValue -Value $required) -or
        @($required | Where-Object {
            $_ -is [string] -and
            [string]::Equals($_, "type", [System.StringComparison]::Ordinal)
        }).Count -eq 0) {
        return $null
    }

    $properties = Get-JsonPropertyValue -Object $Schema -Name "properties"
    if (-not (Test-JsonObjectValue -Value $properties) -or
        -not (Test-JsonProperty -Object $properties -Name "type")) {
        return $null
    }
    $typeProperty = Get-JsonPropertyValue -Object $properties -Name "type"
    if (-not (Test-JsonObjectValue -Value $typeProperty)) {
        return $null
    }
    $propertyType = Get-JsonPropertyValue -Object $typeProperty -Name "type"
    if ($propertyType -isnot [string] -or
        -not [string]::Equals($propertyType, "string", [System.StringComparison]::Ordinal)) {
        return $null
    }

    $enum = Get-JsonPropertyValue -Object $typeProperty -Name "enum"
    if (-not (Test-JsonArrayValue -Value $enum) -or $enum.Count -ne 1) {
        return $null
    }
    $value = $enum[0]
    if ($value -isnot [string]) {
        throw "Type enum value at '$Breadcrumb/properties/type/enum/0' must be a string."
    }

    if (Test-JsonProperty -Object $typeProperty -Name "const") {
        $constValue = Get-JsonPropertyValue -Object $typeProperty -Name "const"
        if ($constValue -isnot [string] -or
            -not [string]::Equals($constValue, $value, [System.StringComparison]::Ordinal)) {
            throw "Type const at '$Breadcrumb/properties/type/const' must equal singleton enum value '$value'."
        }
    }

    return [PSCustomObject]@{
        Value = $value
    }
}

function Get-ValidOpenApiTypeDiscriminatorOneOfPlan {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Schema,

        [Parameter(Mandatory = $true)]
        [string]$Breadcrumb
    )

    $discriminator = Get-JsonPropertyValue -Object $Schema -Name "discriminator"
    if (-not (Test-JsonObjectValue -Value $discriminator)) {
        return $null
    }
    $propertyName = Get-JsonPropertyValue -Object $discriminator -Name "propertyName"
    if ($propertyName -isnot [string] -or
        -not [string]::Equals($propertyName, "type", [System.StringComparison]::Ordinal)) {
        return $null
    }

    return Get-OpenApiInlineDiscriminatorUnionPlan `
        -Schema $Schema `
        -PropertyName "type" `
        -Breadcrumb $Breadcrumb `
        -RequireDiscriminator
}

function Get-OpenApiSingletonTypeEnumScopeKeywordOccurrence {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter(Mandatory = $true)]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context,

        [Parameter(Mandatory = $true)]
        [string]$Breadcrumb,

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "Singleton type scope inspection exceeds the supported depth of $MaximumDepth at '$Breadcrumb'."
    }
    if ($null -eq $Value -or [string]::Equals($Context, "Literal", [System.StringComparison]::Ordinal)) {
        return $null
    }
    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        for ($index = 0; $index -lt $Value.Count; $index++) {
            $occurrence = Get-OpenApiSingletonTypeEnumScopeKeywordOccurrence `
                -Value $Value[$index] `
                -Context $itemContext `
                -Breadcrumb "$Breadcrumb/$index" `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
            if ($null -ne $occurrence) {
                return $occurrence
            }
        }
        return $null
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return $null
    }

    if ([string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal)) {
        foreach ($keyword in @('$id', '$anchor', '$dynamicAnchor', '$recursiveAnchor')) {
            if (Test-JsonProperty -Object $Value -Name $keyword) {
                return [PSCustomObject]@{
                    Keyword = $keyword
                    Breadcrumb = "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $keyword)"
                }
            }
        }
    }

    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        $occurrence = Get-OpenApiSingletonTypeEnumScopeKeywordOccurrence `
            -Value $property.Value `
            -Context $childContext `
            -Breadcrumb "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)" `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
        if ($null -ne $occurrence) {
            return $occurrence
        }
    }
    return $null
}

function Assert-OpenApiSingletonTypeEnumCandidateIsSafe {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Schema,

        [Parameter(Mandatory = $true)]
        [string]$Breadcrumb
    )

    $occurrence = Get-OpenApiSingletonTypeEnumScopeKeywordOccurrence `
        -Value $Schema `
        -Context Schema `
        -Breadcrumb $Breadcrumb
    if ($null -ne $occurrence) {
        throw "Cannot wrap schema at '$Breadcrumb' because scope-sensitive keyword '$($occurrence.Keyword)' at '$($occurrence.Breadcrumb)' would move beneath a oneOf wrapper."
    }
}

function Add-OpenApiSingletonTypeEnumPointerRelocation {
    param(
        [Parameter(Mandatory = $true)]
        [System.Collections.Generic.Dictionary[string, string]]$Relocations,

        [Parameter(Mandatory = $true)]
        [string]$SourcePrefix,

        [Parameter(Mandatory = $true)]
        [string]$DestinationPrefix
    )

    if (-not [string]::Equals($SourcePrefix, $DestinationPrefix, [System.StringComparison]::Ordinal)) {
        Add-OpenApiPointerRelocation `
            -Relocations $Relocations `
            -SourcePrefix $SourcePrefix `
            -DestinationPrefix $DestinationPrefix
    }
}

function Get-DirectlyRelocatedOpenApiSingletonTypeEnumPointer {
    param(
        [Parameter(Mandatory = $true)]
        [string]$Pointer,

        [Parameter(Mandatory = $true)]
        [System.Collections.Generic.Dictionary[string, string]]$Relocations
    )

    if (-not $Pointer.StartsWith("#/", [System.StringComparison]::Ordinal)) {
        return $Pointer
    }
    $canonicalPointer = Get-CanonicalJsonPointer -Pointer $Pointer
    $matchingPrefix = $null
    foreach ($sourcePrefix in $Relocations.Keys) {
        if (($canonicalPointer.Length -eq $sourcePrefix.Length -or
            ($canonicalPointer.Length -gt $sourcePrefix.Length -and
                $canonicalPointer[$sourcePrefix.Length] -eq '/')) -and
            $canonicalPointer.StartsWith($sourcePrefix, [System.StringComparison]::Ordinal) -and
            ($null -eq $matchingPrefix -or $sourcePrefix.Length -gt $matchingPrefix.Length)) {
            $matchingPrefix = $sourcePrefix
        }
    }
    if ($null -eq $matchingPrefix) {
        return $Pointer
    }
    return $Relocations[$matchingPrefix] +
        $canonicalPointer.Substring($matchingPrefix.Length)
}

function ConvertTo-DirectlyRelocatedOpenApiSingletonTypeEnumPointers {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter(Mandatory = $true)]
        [System.Collections.Generic.Dictionary[string, string]]$Relocations,

        [Parameter()]
        [ValidateSet("Default", "Discriminator", "Mapping")]
        [string]$Context = "Default",

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "Singleton type pointer relocation exceeds the supported depth of $MaximumDepth."
    }
    if ($null -eq $Value) {
        return $null
    }
    if (Test-JsonArrayValue -Value $Value) {
        [object[]]$items = [object[]]::new($Value.Count)
        for ($index = 0; $index -lt $Value.Count; $index++) {
            $items[$index] = ConvertTo-DirectlyRelocatedOpenApiSingletonTypeEnumPointers `
                -Value $Value[$index] `
                -Relocations $Relocations `
                -Context Default `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return ,$items
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return $Value
    }

    $result = [ordered]@{}
    foreach ($property in (Get-JsonProperties -Value $Value)) {
        if ([string]::Equals($Context, "Mapping", [System.StringComparison]::Ordinal) -and
            $property.Value -is [string]) {
            $result[$property.Name] = Get-DirectlyRelocatedOpenApiSingletonTypeEnumPointer `
                -Pointer $property.Value `
                -Relocations $Relocations
            continue
        }
        if (@('$ref', '$dynamicRef', '$recursiveRef') -ccontains $property.Name -and
            $property.Value -is [string]) {
            $result[$property.Name] = Get-DirectlyRelocatedOpenApiSingletonTypeEnumPointer `
                -Pointer $property.Value `
                -Relocations $Relocations
            continue
        }

        $childContext = "Default"
        if ([string]::Equals($Context, "Default", [System.StringComparison]::Ordinal) -and
            [string]::Equals($property.Name, "discriminator", [System.StringComparison]::Ordinal)) {
            $childContext = "Discriminator"
        }
        elseif ([string]::Equals($Context, "Discriminator", [System.StringComparison]::Ordinal) -and
            [string]::Equals($property.Name, "mapping", [System.StringComparison]::Ordinal)) {
            $childContext = "Mapping"
        }

        $result[$property.Name] = ConvertTo-DirectlyRelocatedOpenApiSingletonTypeEnumPointers `
            -Value $property.Value `
            -Relocations $Relocations `
            -Context $childContext `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
    return $result
}

function Add-OpenApiSingletonTypeEnumDirectChildRelocations {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Schema,

        [Parameter(Mandatory = $true)]
        [string]$SourceBreadcrumb,

        [Parameter(Mandatory = $true)]
        [string]$DestinationBreadcrumb,

        [Parameter(Mandatory = $true)]
        [System.Collections.Generic.Dictionary[string, string]]$Relocations
    )

    foreach ($property in (Get-JsonProperties -Value $Schema)) {
        $token = ConvertTo-JsonPointerToken -Token $property.Name
        Add-OpenApiSingletonTypeEnumPointerRelocation `
            -Relocations $Relocations `
            -SourcePrefix "$SourceBreadcrumb/$token" `
            -DestinationPrefix "$DestinationBreadcrumb/oneOf/0/$token"
    }
}

function New-OpenApiSingletonTypeEnumDiscriminatorWrapper {
    param(
        [Parameter(Mandatory = $true)]
        [AllowEmptyCollection()]
        [object[]]$Branches,

        [Parameter(Mandatory = $true)]
        [string]$Breadcrumb
    )

    $wrapper = [ordered]@{
        discriminator = [ordered]@{ propertyName = "type" }
        oneOf = [object[]]$Branches
    }
    $plan = Get-OpenApiInlineDiscriminatorUnionPlan `
        -Schema $wrapper `
        -PropertyName "type" `
        -Breadcrumb $Breadcrumb `
        -RequireDiscriminator
    if ($null -eq $plan) {
        throw "Generated singleton type wrapper at '$Breadcrumb' is not a valid type-discriminated oneOf."
    }
    return $wrapper
}

function ConvertTo-WrappedOpenApiSingletonTypeEnumValue {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter(Mandatory = $true)]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context,

        [Parameter(Mandatory = $true)]
        [string]$SourceBreadcrumb,

        [Parameter(Mandatory = $true)]
        [string]$DestinationBreadcrumb,

        [Parameter(Mandatory = $true)]
        [System.Collections.Generic.Dictionary[string, string]]$Relocations,

        [Parameter(Mandatory = $true)]
        [ref]$WrappedSchemaCount,

        [Parameter(Mandatory = $true)]
        [ref]$GroupedOneOfCount,

        [Parameter(Mandatory = $true)]
        [ref]$GroupedBranchCount,

        [Parameter(Mandatory = $true)]
        [ref]$SingletonWrapperCount,

        [Parameter()]
        [switch]$SuppressCurrentCandidate,

        [Parameter()]
        [switch]$DirectBranchOfValidTypeOneOf,

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "Singleton type wrapping exceeds the supported depth of $MaximumDepth at '$SourceBreadcrumb'."
    }
    if ($null -eq $Value) {
        return $null
    }
    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        [object[]]$items = [object[]]::new($Value.Count)
        for ($index = 0; $index -lt $Value.Count; $index++) {
            $items[$index] = ConvertTo-WrappedOpenApiSingletonTypeEnumValue `
                -Value $Value[$index] `
                -Context $itemContext `
                -SourceBreadcrumb "$SourceBreadcrumb/$index" `
                -DestinationBreadcrumb "$DestinationBreadcrumb/$index" `
                -Relocations $Relocations `
                -WrappedSchemaCount $WrappedSchemaCount `
                -GroupedOneOfCount $GroupedOneOfCount `
                -GroupedBranchCount $GroupedBranchCount `
                -SingletonWrapperCount $SingletonWrapperCount `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return ,$items
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return $Value
    }
    if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
        $Context = "Schema"
    }

    $isSchema = [string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal)
    $candidatePlan = if ($isSchema -and -not $SuppressCurrentCandidate) {
        Get-WrappableOpenApiSingletonTypeEnumPlan `
            -Schema $Value `
            -Breadcrumb $SourceBreadcrumb
    }
    else {
        $null
    }
    if ($null -ne $candidatePlan -and -not $DirectBranchOfValidTypeOneOf) {
        Assert-OpenApiSingletonTypeEnumCandidateIsSafe `
            -Schema $Value `
            -Breadcrumb $SourceBreadcrumb
        Add-OpenApiSingletonTypeEnumDirectChildRelocations `
            -Schema $Value `
            -SourceBreadcrumb $SourceBreadcrumb `
            -DestinationBreadcrumb $DestinationBreadcrumb `
            -Relocations $Relocations
        $leafDestination = "$DestinationBreadcrumb/oneOf/0"
        $leaf = ConvertTo-WrappedOpenApiSingletonTypeEnumValue `
            -Value $Value `
            -Context Schema `
            -SourceBreadcrumb $SourceBreadcrumb `
            -DestinationBreadcrumb $leafDestination `
            -Relocations $Relocations `
            -WrappedSchemaCount $WrappedSchemaCount `
            -GroupedOneOfCount $GroupedOneOfCount `
            -GroupedBranchCount $GroupedBranchCount `
            -SingletonWrapperCount $SingletonWrapperCount `
            -SuppressCurrentCandidate `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
        $WrappedSchemaCount.Value++
        $SingletonWrapperCount.Value++
        return New-OpenApiSingletonTypeEnumDiscriminatorWrapper `
            -Branches @($leaf) `
            -Breadcrumb $DestinationBreadcrumb
    }

    $oneOf = if ($isSchema) { Get-JsonPropertyValue -Object $Value -Name "oneOf" } else { $null }
    $validTypePlan = if (Test-JsonArrayValue -Value $oneOf) {
        Get-ValidOpenApiTypeDiscriminatorOneOfPlan `
            -Schema $Value `
            -Breadcrumb $SourceBreadcrumb
    }
    else {
        $null
    }

    $groupedBranchPlans = [System.Collections.Generic.Dictionary[int, object]]::new()
    $wrapGroupedBranchesSeparately = $false
    if ((Test-JsonArrayValue -Value $oneOf) -and $null -eq $validTypePlan) {
        for ($index = 0; $index -lt $oneOf.Count; $index++) {
            $plan = Get-WrappableOpenApiSingletonTypeEnumPlan `
                -Schema $oneOf[$index] `
                -Breadcrumb "$SourceBreadcrumb/oneOf/$index"
            if ($null -ne $plan) {
                $groupedBranchPlans[$index] = $plan
            }
        }
        if ($groupedBranchPlans.Count -gt 0) {
            $discriminator = Get-JsonPropertyValue -Object $Value -Name "discriminator"
            if (Test-JsonObjectValue -Value $discriminator) {
                $propertyName = Get-JsonPropertyValue -Object $discriminator -Name "propertyName"
                throw "Cannot group singleton type branches at '$SourceBreadcrumb/oneOf' because the parent has incompatible discriminator propertyName '$propertyName'."
            }
            $inferredPlan = Get-OpenApiInlineDiscriminatorUnionPlan `
                -Schema $Value `
                -PropertyName "type" `
                -Breadcrumb $SourceBreadcrumb
            if ($null -ne $inferredPlan) {
                throw "Cannot group singleton type branches at '$SourceBreadcrumb/oneOf' because the parent remains eligible for direct type discriminator inference. Run Add-OpenApiOneOfDiscriminators.ps1 first."
            }
            $seenValues = [System.Collections.Generic.Dictionary[string, string]]::new(
                [System.StringComparer]::Ordinal
            )
            foreach ($entry in $groupedBranchPlans.GetEnumerator()) {
                $valueName = [string]$entry.Value.Value
                $branchBreadcrumb = "$SourceBreadcrumb/oneOf/$($entry.Key)"
                if ($seenValues.ContainsKey($valueName)) {
                    $wrapGroupedBranchesSeparately = $true
                }
                else {
                    $seenValues[$valueName] = $branchBreadcrumb
                }
            }
        }
    }

    $result = [ordered]@{}
    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $token = ConvertTo-JsonPointerToken -Token $property.Name
        $sourceChildBreadcrumb = "$SourceBreadcrumb/$token"
        $destinationChildBreadcrumb = "$DestinationBreadcrumb/$token"
        if ($isSchema -and
            [string]::Equals($property.Name, "oneOf", [System.StringComparison]::Ordinal) -and
            (Test-JsonArrayValue -Value $property.Value)) {
            if ($groupedBranchPlans.Count -gt 0) {
                if ($wrapGroupedBranchesSeparately) {
                    $outputBranches = [System.Collections.Generic.List[object]]::new()
                    for ($index = 0; $index -lt $property.Value.Count; $index++) {
                        $sourceBranch = "$sourceChildBreadcrumb/$index"
                        $destinationBranch = "$destinationChildBreadcrumb/$($outputBranches.Count)"
                        if ($groupedBranchPlans.ContainsKey($index)) {
                            $leafDestination = "$destinationBranch/oneOf/0"
                            Assert-OpenApiSingletonTypeEnumCandidateIsSafe `
                                -Schema $property.Value[$index] `
                                -Breadcrumb $sourceBranch
                            Add-OpenApiSingletonTypeEnumPointerRelocation `
                                -Relocations $Relocations `
                                -SourcePrefix $sourceBranch `
                                -DestinationPrefix $leafDestination
                            $leaf = ConvertTo-WrappedOpenApiSingletonTypeEnumValue `
                                -Value $property.Value[$index] `
                                -Context Schema `
                                -SourceBreadcrumb $sourceBranch `
                                -DestinationBreadcrumb $leafDestination `
                                -Relocations $Relocations `
                                -WrappedSchemaCount $WrappedSchemaCount `
                                -GroupedOneOfCount $GroupedOneOfCount `
                                -GroupedBranchCount $GroupedBranchCount `
                                -SingletonWrapperCount $SingletonWrapperCount `
                                -SuppressCurrentCandidate `
                                -Depth ($Depth + 1) `
                                -MaximumDepth $MaximumDepth
                            $outputBranches.Add((New-OpenApiSingletonTypeEnumDiscriminatorWrapper `
                                -Branches @($leaf) `
                                -Breadcrumb $destinationBranch))
                            $WrappedSchemaCount.Value++
                            $SingletonWrapperCount.Value++
                            continue
                        }

                        Add-OpenApiSingletonTypeEnumPointerRelocation `
                            -Relocations $Relocations `
                            -SourcePrefix $sourceBranch `
                            -DestinationPrefix $destinationBranch
                        $outputBranches.Add((ConvertTo-WrappedOpenApiSingletonTypeEnumValue `
                            -Value $property.Value[$index] `
                            -Context Schema `
                            -SourceBreadcrumb $sourceBranch `
                            -DestinationBreadcrumb $destinationBranch `
                            -Relocations $Relocations `
                            -WrappedSchemaCount $WrappedSchemaCount `
                            -GroupedOneOfCount $GroupedOneOfCount `
                            -GroupedBranchCount $GroupedBranchCount `
                            -SingletonWrapperCount $SingletonWrapperCount `
                            -Depth ($Depth + 1) `
                            -MaximumDepth $MaximumDepth))
                    }
                    $result[$property.Name] = [object[]]$outputBranches.ToArray()
                    continue
                }

                $outputBranches = [System.Collections.Generic.List[object]]::new()
                $groupedBranches = [System.Collections.Generic.List[object]]::new()
                $firstGroupedOutputIndex = -1
                for ($index = 0; $index -lt $property.Value.Count; $index++) {
                    $sourceBranch = "$sourceChildBreadcrumb/$index"
                    if ($groupedBranchPlans.ContainsKey($index)) {
                        if ($firstGroupedOutputIndex -lt 0) {
                            $firstGroupedOutputIndex = $outputBranches.Count
                        }
                        $destinationBranch = "$destinationChildBreadcrumb/$firstGroupedOutputIndex/oneOf/$($groupedBranches.Count)"
                        Assert-OpenApiSingletonTypeEnumCandidateIsSafe `
                            -Schema $property.Value[$index] `
                            -Breadcrumb $sourceBranch
                        Add-OpenApiSingletonTypeEnumPointerRelocation `
                            -Relocations $Relocations `
                            -SourcePrefix $sourceBranch `
                            -DestinationPrefix $destinationBranch
                        $groupedBranches.Add((ConvertTo-WrappedOpenApiSingletonTypeEnumValue `
                            -Value $property.Value[$index] `
                            -Context Schema `
                            -SourceBreadcrumb $sourceBranch `
                            -DestinationBreadcrumb $destinationBranch `
                            -Relocations $Relocations `
                            -WrappedSchemaCount $WrappedSchemaCount `
                            -GroupedOneOfCount $GroupedOneOfCount `
                            -GroupedBranchCount $GroupedBranchCount `
                            -SingletonWrapperCount $SingletonWrapperCount `
                            -SuppressCurrentCandidate `
                            -Depth ($Depth + 1) `
                            -MaximumDepth $MaximumDepth))
                        continue
                    }

                    $destinationIndex = $outputBranches.Count
                    if ($firstGroupedOutputIndex -ge 0) {
                        $destinationIndex++
                    }
                    $destinationBranch = "$destinationChildBreadcrumb/$destinationIndex"
                    Add-OpenApiSingletonTypeEnumPointerRelocation `
                        -Relocations $Relocations `
                        -SourcePrefix $sourceBranch `
                        -DestinationPrefix $destinationBranch
                    $outputBranches.Add((ConvertTo-WrappedOpenApiSingletonTypeEnumValue `
                        -Value $property.Value[$index] `
                        -Context Schema `
                        -SourceBreadcrumb $sourceBranch `
                        -DestinationBreadcrumb $destinationBranch `
                        -Relocations $Relocations `
                        -WrappedSchemaCount $WrappedSchemaCount `
                        -GroupedOneOfCount $GroupedOneOfCount `
                        -GroupedBranchCount $GroupedBranchCount `
                        -SingletonWrapperCount $SingletonWrapperCount `
                        -Depth ($Depth + 1) `
                        -MaximumDepth $MaximumDepth))
                }
                $wrapperBreadcrumb = "$destinationChildBreadcrumb/$firstGroupedOutputIndex"
                $wrapper = New-OpenApiSingletonTypeEnumDiscriminatorWrapper `
                    -Branches ([object[]]$groupedBranches.ToArray()) `
                    -Breadcrumb $wrapperBreadcrumb
                $outputBranches.Insert($firstGroupedOutputIndex, $wrapper)
                $WrappedSchemaCount.Value += $groupedBranches.Count
                $GroupedOneOfCount.Value++
                $GroupedBranchCount.Value += $groupedBranches.Count
                $result[$property.Name] = [object[]]$outputBranches.ToArray()
                continue
            }

            [object[]]$branches = [object[]]::new($property.Value.Count)
            for ($index = 0; $index -lt $property.Value.Count; $index++) {
                $branchSource = "$sourceChildBreadcrumb/$index"
                $branchDestination = "$destinationChildBreadcrumb/$index"
                $branches[$index] = ConvertTo-WrappedOpenApiSingletonTypeEnumValue `
                    -Value $property.Value[$index] `
                    -Context Schema `
                    -SourceBreadcrumb $branchSource `
                    -DestinationBreadcrumb $branchDestination `
                    -Relocations $Relocations `
                    -WrappedSchemaCount $WrappedSchemaCount `
                    -GroupedOneOfCount $GroupedOneOfCount `
                    -GroupedBranchCount $GroupedBranchCount `
                    -SingletonWrapperCount $SingletonWrapperCount `
                    -DirectBranchOfValidTypeOneOf:($null -ne $validTypePlan) `
                    -Depth ($Depth + 1) `
                    -MaximumDepth $MaximumDepth
            }
            $result[$property.Name] = $branches
            continue
        }

        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        $result[$property.Name] = ConvertTo-WrappedOpenApiSingletonTypeEnumValue `
            -Value $property.Value `
            -Context $childContext `
            -SourceBreadcrumb $sourceChildBreadcrumb `
            -DestinationBreadcrumb $destinationChildBreadcrumb `
            -Relocations $Relocations `
            -WrappedSchemaCount $WrappedSchemaCount `
            -GroupedOneOfCount $GroupedOneOfCount `
            -GroupedBranchCount $GroupedBranchCount `
            -SingletonWrapperCount $SingletonWrapperCount `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
    return $result
}

function Assert-NoUnwrappedOpenApiSingletonTypeEnums {
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Value,

        [Parameter()]
        [ValidateSet("OpenApi", "Components", "SchemaMap", "SchemaArray", "Schema", "Literal")]
        [string]$Context = "OpenApi",

        [Parameter()]
        [string]$Breadcrumb = "#",

        [Parameter()]
        [switch]$DirectBranchOfValidTypeOneOf,

        [Parameter()]
        [int]$Depth = 0,

        [Parameter()]
        [int]$MaximumDepth = 200
    )

    if ($Depth -gt $MaximumDepth) {
        throw "Singleton type wrapper postcondition exceeds the supported depth of $MaximumDepth at '$Breadcrumb'."
    }
    if ($null -eq $Value) {
        return
    }
    if (Test-JsonArrayValue -Value $Value) {
        $itemContext = $Context
        if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
            $itemContext = "Schema"
        }
        for ($index = 0; $index -lt $Value.Count; $index++) {
            Assert-NoUnwrappedOpenApiSingletonTypeEnums `
                -Value $Value[$index] `
                -Context $itemContext `
                -Breadcrumb "$Breadcrumb/$index" `
                -Depth ($Depth + 1) `
                -MaximumDepth $MaximumDepth
        }
        return
    }
    if (-not (Test-JsonObjectValue -Value $Value)) {
        return
    }
    if ([string]::Equals($Context, "SchemaArray", [System.StringComparison]::Ordinal)) {
        $Context = "Schema"
    }

    $isSchema = [string]::Equals($Context, "Schema", [System.StringComparison]::Ordinal)
    if ($isSchema -and -not $DirectBranchOfValidTypeOneOf -and
        $null -ne (Get-WrappableOpenApiSingletonTypeEnumPlan -Schema $Value -Breadcrumb $Breadcrumb)) {
        throw "Wrapped output retained required singleton type enum outside a valid type-discriminated oneOf at '$Breadcrumb'."
    }

    $oneOf = if ($isSchema) { Get-JsonPropertyValue -Object $Value -Name "oneOf" } else { $null }
    $validPlan = if (Test-JsonArrayValue -Value $oneOf) {
        Get-ValidOpenApiTypeDiscriminatorOneOfPlan -Schema $Value -Breadcrumb $Breadcrumb
    }
    else {
        $null
    }

    foreach ($property in (Get-JsonProperties -Value $Value)) {
        $propertyBreadcrumb = "$Breadcrumb/$(ConvertTo-JsonPointerToken -Token $property.Name)"
        $childContext = Get-OpenApiSchemaChildContext `
            -ParentContext $Context `
            -PropertyName $property.Name `
            -PropertyValue $property.Value
        if ($isSchema -and
            [string]::Equals($property.Name, "oneOf", [System.StringComparison]::Ordinal) -and
            (Test-JsonArrayValue -Value $property.Value)) {
            for ($index = 0; $index -lt $property.Value.Count; $index++) {
                Assert-NoUnwrappedOpenApiSingletonTypeEnums `
                    -Value $property.Value[$index] `
                    -Context Schema `
                    -Breadcrumb "$propertyBreadcrumb/$index" `
                    -DirectBranchOfValidTypeOneOf:($null -ne $validPlan) `
                    -Depth ($Depth + 1) `
                    -MaximumDepth $MaximumDepth
            }
            continue
        }
        Assert-NoUnwrappedOpenApiSingletonTypeEnums `
            -Value $property.Value `
            -Context $childContext `
            -Breadcrumb $propertyBreadcrumb `
            -Depth ($Depth + 1) `
            -MaximumDepth $MaximumDepth
    }
}

function ConvertTo-WrappedOpenApiSingletonTypeEnumDocument {
    param(
        [Parameter(Mandatory = $true)]
        [object]$Document
    )

    $relocations = [System.Collections.Generic.Dictionary[string, string]]::new(
        [System.StringComparer]::Ordinal
    )
    $wrappedSchemaCount = 0
    $groupedOneOfCount = 0
    $groupedBranchCount = 0
    $singletonWrapperCount = 0
    $converted = ConvertTo-WrappedOpenApiSingletonTypeEnumValue `
        -Value $Document `
        -Context OpenApi `
        -SourceBreadcrumb "#" `
        -DestinationBreadcrumb "#" `
        -Relocations $relocations `
        -WrappedSchemaCount ([ref]$wrappedSchemaCount) `
        -GroupedOneOfCount ([ref]$groupedOneOfCount) `
        -GroupedBranchCount ([ref]$groupedBranchCount) `
        -SingletonWrapperCount ([ref]$singletonWrapperCount)
    $relocated = ConvertTo-DirectlyRelocatedOpenApiSingletonTypeEnumPointers `
        -Value $converted `
        -Relocations $relocations

    Assert-OpenApiReferencesResolve -Document $relocated
    Assert-AdditionalOpenApiReferencesResolve -Document $relocated
    Assert-NoUnwrappedOpenApiSingletonTypeEnums -Value $relocated

    return [PSCustomObject]@{
        Document = $relocated
        WrappedSchemaCount = $wrappedSchemaCount
        GroupedOneOfCount = $groupedOneOfCount
        GroupedBranchCount = $groupedBranchCount
        SingletonWrapperCount = $singletonWrapperCount
        GeneratedWrapperCount = $groupedOneOfCount + $singletonWrapperCount
        RelocationCount = $relocations.Count
    }
}

function Get-DefaultWrappedOpenApiSingletonTypeEnumPath {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath
    )

    $fullInputPath = [System.IO.Path]::GetFullPath($InputPath)
    $directory = [System.IO.Path]::GetDirectoryName($fullInputPath)
    $fileName = [System.IO.Path]::GetFileName($fullInputPath)
    if ($fileName.EndsWith(".singleton-type-wrapped.openapi.json", [System.StringComparison]::OrdinalIgnoreCase) -or
        $fileName.EndsWith(".singleton-type-wrapped.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        return $fullInputPath
    }
    if ($fileName.EndsWith(".openapi.json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $baseName = $fileName.Substring(0, $fileName.Length - ".openapi.json".Length)
        return Join-Path $directory "$baseName.singleton-type-wrapped.openapi.json"
    }
    if ($fileName.EndsWith(".json", [System.StringComparison]::OrdinalIgnoreCase)) {
        $baseName = $fileName.Substring(0, $fileName.Length - ".json".Length)
        return Join-Path $directory "$baseName.singleton-type-wrapped.json"
    }
    return Join-Path $directory "$fileName.singleton-type-wrapped.json"
}

function Invoke-OpenApiSingletonTypeEnumWrapper {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InputPath,

        [Parameter()]
        [string]$OutputPath
    )

    $resolvedInputPath = (Resolve-Path -LiteralPath $InputPath -ErrorAction Stop).ProviderPath
    if (-not [System.IO.File]::Exists($resolvedInputPath)) {
        throw "The OpenAPI input path is not a file: $resolvedInputPath"
    }
    if ([string]::IsNullOrWhiteSpace($OutputPath)) {
        $OutputPath = Get-DefaultWrappedOpenApiSingletonTypeEnumPath -InputPath $resolvedInputPath
    }
    else {
        $OutputPath = [System.IO.Path]::GetFullPath($OutputPath)
    }

    $document = Read-OpenApiDocument -Path $resolvedInputPath
    $result = ConvertTo-WrappedOpenApiSingletonTypeEnumDocument -Document $document
    $writtenPath = Write-OpenApiJsonFile -Document $result.Document -Path $OutputPath

    Write-Host ""
    Write-Host "Input: $resolvedInputPath"
    Write-Host "Output: $writtenPath"
    Write-Host "Typed object schemas wrapped: $($result.WrappedSchemaCount)"
    Write-Host "Mixed oneOf groups created: $($result.GroupedOneOfCount)"
    Write-Host "Object branches grouped: $($result.GroupedBranchCount)"
    Write-Host "Singleton wrappers created: $($result.SingletonWrapperCount)"
    Write-Host "Discriminator wrappers generated: $($result.GeneratedWrapperCount)"
    Write-Host "JSON Pointer prefixes relocated: $($result.RelocationCount)"

    return $result
}

if ($MyInvocation.InvocationName -ne ".") {
    if ([string]::IsNullOrWhiteSpace($InputPath)) {
        throw "InputPath is required."
    }
    $null = Invoke-OpenApiSingletonTypeEnumWrapper `
        -InputPath $InputPath `
        -OutputPath $OutputPath
}
